# Regenerate images.txt from the charts. Run from the repo root.
# The list is generated rather than maintained so it cannot drift.
set -euo pipefail
# NOTE: a missing required value plus `2>/dev/null || true` once silently
# dropped the ENTIRE platform layer from this list. 14 images, all storage,
# ingress, LB and certs. Never swallow a render failure in a generator.
# Render values come from ci/values.yaml ... one file, same as CI, so a value
# added there is a value added here.
cd "$(dirname "$0")/.."
# The image extractor, shared with check-airgap.sh. See TM-0646 and the header
# of that file. Prove it with `bash tools/lib/extract-images.sh --selftest`.
. "$(dirname "$0")/lib/extract-images.sh"

# WRITE TO A TEMP FILE AND MOVE ON SUCCESS. `{ ... } > images.txt` truncates the
# target BEFORE the block runs, so a render failure inside the loop leaves the
# file holding three comment lines and nothing else ... the script exits 1, but
# the damage is already done, and the zero-image guard at the bottom never runs
# because the `exit 1` in the loop fires first. Measured 2026-09-12: the AI layer
# failed to render during the version bump and images.txt lost 45 of 45 entries.
#
# images.txt is the air-gap mirror list. A truncated one that reaches a tag means
# an air-gapped install pulls nothing and fails very far from here. TM-0520.
OUT="$(mktemp "${TMPDIR:-/tmp}/tockmox-images.XXXXXX")"
trap 'rm -f "$OUT"' EXIT
{
  echo "# Container images referenced by Tockmox charts."
  echo "# Generated by tools/gen-images.sh on $(date -u +%Y-%m-%d). Do not edit by hand."
  echo "#"
  for c in charts/tockmox-*; do
    [ "$c" = "charts/tockmox-common" ] && continue
    helm dependency build "$c" >/dev/null 2>&1 || true
    # --skip-tests, and NOT --no-hooks. `helm template` renders hook resources
    # by default, which is correct for this list: the LiteLLM migration Job and
    # the Garage bootstrap and credentials Jobs are all hooks, they all really
    # deploy, and an airgap mirror that omits their images fails at install.
    #
    # TEST hooks are the exception. The LiteLLM subchart's two `helm test` pods
    # hardcode `image: busybox`, with no tag and no values override, and they
    # only ever run if somebody types `helm test`. Argo never does. Before this
    # flag, images.txt carried a bare `busybox` alongside a properly pinned
    # docker.io/library/busybox:1.38.0 ... so an operator mirroring the list
    # pulled `latest` for a code path that never executes, which is both
    # non-reproducible and the only unpinned entry in the file.
    #
    # --no-hooks would have fixed the symptom and dropped the three real Jobs
    # with it.
    helm template t "$c" \
      -f ci/values.yaml \
      --skip-tests \
      || { echo "RENDER FAILED for $c" >&2; exit 1; }
  # ONE extractor, shared with check-airgap.sh (tools/lib/extract-images.sh,
  # TM-0646). It used to be a copy of that pipeline, and the copies had drifted:
  # this one used `\s`, which is a GNU extension that BSD `grep -E` ... the grep
  # on macOS ... does not honour. The gate that checks the mirror list and the
  # generator that writes it were not reading the same manifests, and on Linux
  # CI that was invisible. The quote handling and its reasoning now live in that
  # file, next to the self-test that proves it.
  done | extract_images
} > "$OUT"
# Both guards run BEFORE the move, so a bad result never reaches images.txt.
n=$(grep -cv '^#' "$OUT" || true)
[ "$n" -eq 0 ] && { echo "ERROR: zero images from nine implemented layers" >&2; exit 1; }
mv "$OUT" images.txt
trap - EXIT
echo "images.txt written: $n image(s)"
exit 0
