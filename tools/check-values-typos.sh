#
# A MISSPELT SWITCH MUST NOT RENDER CLEAN.
#
# Every layer schema closes its root, so `opnWebui: ...` at the top level is an
# error. Until TM-0404 that was the only level a typo was caught at, and it is
# the level an operator edits least. The keys an operator actually types are
# the feature switches under `apps`, and there a misspelt component name
# rendered clean and silently did nothing:
#
#   --set totallyBogusRootKey=true        REJECTED   (the root, closed)
#   --set apps.open_webui.enabled=true    ACCEPTED   (TM-0290's real defect)
#   --set apps.openwebui.enabled=true     ACCEPTED   (case)
#
# WHY A SHARED LIST AND NOT ONE LIST PER LAYER. The values namespace is shared
# across all nine layers: a profile is one file passed to every layer, and
# profiles/minimal.yaml sets apps.longhorn (platform) and apps.authentik
# (identity) in the same block. A per-layer list would reject the profile on
# seven layers. So each layer's `apps` accepts every component name ANY layer
# declares and nothing else, which is the same design the root already uses for
# top-level keys (values-contract.md, "Keys belonging to another layer"). The
# cost is the same too: a component set on the wrong layer is silent. A name
# that exists nowhere is not.
#
# THE LIST IS GENERATED, from the `apps:` maps in charts/*/values.yaml, and
# written into each schema as `apps.propertyNames.enum`. Adding a component to
# a layer's values.yaml without regenerating fails this gate, which is the
# point: the alternative is a new component every schema silently rejects.
#
# TWO ASSERTIONS, plus a control, per layer:
#   1. SYNC.   every schema's enum equals a fresh render of the union.
#   2. POISON. an unknown top-level key, a snake-case component name and a
#              lower-case component name are each REJECTED.
#   3. CONTROL a correctly spelt component of that layer is ACCEPTED, so a
#              layer that rejects everything (a broken fixture, a missing
#              dependency) reads as a failure rather than as three passes.
#
# Usage:
#   tools/check-values-typos.sh            all assertions
#   tools/check-values-typos.sh --write    regenerate the enum in every schema
#   tools/check-values-typos.sh --selftest prove assertions 1 and 2 can go red
set -uo pipefail
cd "$(dirname "$0")/.."

gen() {
  # $1 = check | write ; $2 = charts root (default charts)
  python3 - "$1" "${2:-charts}" <<'PY'
import glob, json, sys, yaml
mode, root = sys.argv[1], sys.argv[2]
names = set()
for vf in sorted(glob.glob(f"{root}/tockmox-*/values.yaml")):
    with open(vf) as fh:
        names |= set(((yaml.safe_load(fh) or {}).get("apps") or {}).keys())
enum = sorted(names)
bad = 0
for sf in sorted(glob.glob(f"{root}/tockmox-*/values.schema.json")):
    with open(sf) as fh:
        text = fh.read()
    s = json.loads(text)
    apps = s.get("properties", {}).get("apps")
    if apps is None:
        print(f"  {sf}: no apps block"); bad = 1; continue
    have = (apps.get("propertyNames") or {}).get("enum")
    if mode == "write":
        apps["propertyNames"] = {
            "enum": enum,
            "description": "Generated by tools/check-values-typos.sh --write: every component name any layer declares (TM-0404).",
        }
        new = json.dumps(s, indent=2, ensure_ascii=False) + "\n"
        if new != text:
            with open(sf, "w") as fh:
                fh.write(new)
            print(f"  wrote {sf}")
    elif have != enum:
        missing = sorted(set(enum) - set(have or []))
        extra = sorted(set(have or []) - set(enum))
        print(f"  {sf}: apps.propertyNames.enum is stale ({len(missing)} missing, e.g. {missing[:3]}; {len(extra)} extra, e.g. {extra[:3]})")
        bad = 1
print(f"  {len(enum)} component names across the layers")
sys.exit(bad)
PY
}

lint() { helm lint "$@" >/dev/null 2>&1; }

poison() {
  # $1 = charts root. Echoes one line per failure, returns non-zero on any.
  local root="${1:-charts}" rc=0 c layer good
  for c in "$root"/tockmox-*; do
    [ -f "$c/values.schema.json" ] || continue
    layer="$(basename "$c")"
    good="$(python3 -c 'import sys,yaml; a=(yaml.safe_load(open(sys.argv[1])) or {}).get("apps") or {}; print(sorted(a)[0] if a else "")' "$c/values.yaml")"
    if [ -z "$good" ]; then echo "  $layer: declares no apps component to use as a control"; rc=1; continue; fi
    lint "$c" -f ci/values.yaml --set "apps.${good}.enabled=true" \
      || { echo "  $layer: CONTROL apps.${good}.enabled=true was rejected; the poison results below mean nothing"; rc=1; continue; }
    lint "$c" -f ci/values.yaml --set thisKeyDoesNotExist.at.all=1 \
      && { echo "  $layer: accepted an unknown top-level key"; rc=1; }
    lint "$c" -f ci/values.yaml --set apps.open_webui.enabled=true \
      && { echo "  $layer: accepted the misspelt component apps.open_webui"; rc=1; }
    lint "$c" -f ci/values.yaml --set apps.openwebui.enabled=true \
      && { echo "  $layer: accepted the mis-cased component apps.openwebui"; rc=1; }
  done
  return $rc
}

command -v helm >/dev/null 2>&1 || { echo "check-values-typos: helm is not on PATH; refusing rather than guessing"; exit 2; }
command -v python3 >/dev/null 2>&1 && python3 -c 'import yaml' 2>/dev/null \
  || { echo "check-values-typos: needs python3 with PyYAML"; exit 2; }

case "${1:-}" in
  --write) gen write; exit 0 ;;
  --selftest)
    tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
    ok=1
    cp -R charts "$tmp/charts"
    # SYNC must go red when a layer gains a component nobody regenerated for.
    python3 - "$tmp/charts/tockmox-exporters/values.yaml" <<'PY'
import sys
p = sys.argv[1]
t = open(p).read()
t = t.replace("\napps:\n", "\napps:\n  selftestOnlyComponent:\n    enabled: false\n", 1)
open(p, "w").write(t)
PY
    # Red for SYNC's own reason: a crash in gen also exits non-zero. Name the injected component.
    out="$(gen check "$tmp/charts" 2>&1)"; rc=$?
    if [ "$rc" = 1 ] && grep -qF "is stale (1 missing, e.g. ['selftestOnlyComponent']" <<<"$out"; then
      echo "selftest: SYNC goes red on a stale enum"
    else
      echo "selftest: SYNC did not go red for the right reason on a stale enum (exit $rc):"; printf '%s\n' "$out" | sed 's/^/    /'; ok=0
    fi
    rm -rf "$tmp/charts"; cp -R charts "$tmp/charts"
    # POISON must go red when one layer's enum is removed.
    python3 - "$tmp/charts/tockmox-ai/values.schema.json" <<'PY'
import json, sys
p = sys.argv[1]; s = json.load(open(p))
s["properties"]["apps"].pop("propertyNames", None)
open(p, "w").write(json.dumps(s, indent=2) + "\n")
PY
    ( cd "$tmp" && ln -s "$OLDPWD/ci" ci ) || { echo "selftest: could not link ci/ into the throwaway tree"; ok=0; }
    # poison() exits non-zero for a CONTROL failure (helm rejecting a correct value, which reads as red
    # on every layer), for a layer other than the one broken here, and for each of its own assertions.
    # Any non-zero exit would pass for all of them, so each case below names the exact lines it must print.
    out="$(cd "$tmp" && poison charts)"
    want="  tockmox-ai: accepted the misspelt component apps.open_webui
  tockmox-ai: accepted the mis-cased component apps.openwebui"
    if [ "$out" = "$want" ]; then
      echo "selftest: POISON goes red with tockmox-ai's enum removed"
    else
      echo "selftest: POISON did not go red for the right reason with tockmox-ai's enum removed:"; printf '%s\n' "$out" | sed 's/^/    /'; ok=0
    fi
    # The other two lines poison() can print, which the case above never reaches.
    rm -rf "$tmp/charts"; cp -R charts "$tmp/charts"
    python3 - "$tmp/charts/tockmox-ai/values.schema.json" <<'PY'
import json, sys
p = sys.argv[1]; s = json.load(open(p))
s["additionalProperties"] = True
open(p, "w").write(json.dumps(s, indent=2) + "\n")
PY
    out="$(cd "$tmp" && poison charts)"
    if [ "$out" = "  tockmox-ai: accepted an unknown top-level key" ]; then
      echo "selftest: POISON goes red with tockmox-ai's root opened"
    else
      echo "selftest: POISON did not go red for the right reason with tockmox-ai's root opened:"; printf '%s\n' "$out" | sed 's/^/    /'; ok=0
    fi
    rm -rf "$tmp/charts"; cp -R charts "$tmp/charts"
    python3 - "$tmp/charts/tockmox-ai" <<'PY'
import json, sys, yaml
d = sys.argv[1]; s = json.load(open(d + "/values.schema.json"))
good = sorted(yaml.safe_load(open(d + "/values.yaml"))["apps"])[0]
s["properties"]["apps"]["propertyNames"]["enum"].remove(good)
open(d + "/values.schema.json", "w").write(json.dumps(s, indent=2) + "\n")
PY
    out="$(cd "$tmp" && poison charts)"
    if [ "$(printf '%s\n' "$out" | grep -c .)" = 1 ] && grep -q '^  tockmox-ai: CONTROL apps\.[A-Za-z0-9_]*\.enabled=true was rejected' <<<"$out"; then
      echo "selftest: POISON reports a rejected CONTROL as its own failure"
    else
      echo "selftest: POISON did not report the rejected CONTROL, and only that:"; printf '%s\n' "$out" | sed 's/^/    /'; ok=0
    fi
    [ "$ok" = 1 ] && { echo "check-values-typos --selftest: PASSED"; exit 0; }
    echo "check-values-typos --selftest: FAILED"; exit 1 ;;
  "") ;;
  *) echo "usage: $0 [--write|--selftest]"; exit 2 ;;
esac

rc=0
echo "sync:"
gen check || rc=1
echo "poison (per layer):"
poison charts || rc=1
[ "$rc" = 0 ] && echo "check-values-typos: PASSED" || echo "check-values-typos: FAILED"
exit $rc
