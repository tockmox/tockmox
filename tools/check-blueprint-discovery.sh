#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
#
# Assert that Authentik DISCOVERED AND APPLIED every blueprint this chart ships.
#
#   ./tools/check-blueprint-discovery.sh                # assert, against ci/values.yaml
#   ./tools/check-blueprint-discovery.sh --poison       # make the gate fail
#   ./tools/check-blueprint-discovery.sh --unpoison     # undo that
#
#   --context NAME   the cluster to act on. WITHOUT IT EVERY kubectl HERE
#                    RESOLVES current-context, which is how a release step run
#                    from a workstation reaches production (TM-0634).
#   --yes            skip the confirmation that --poison/--unpoison require.
#                    For automation only; a human should type the context name.
#
# WHY --poison CONFIRMS AND THE READ PATH DOES NOT. `--poison` and `--unpoison`
# CREATE A ConfigMap AND PATCH THE AUTHENTIK WORKER Deployment. Until 2026-09-15
# the only thing standing between `--poison` and a production identity layer was
# the coincidence that the target cluster had no namespace called
# `tockmox-authentik`; the script printed its context but did not gate on it.
# A printed context is not a control. The read path is unchanged: it only reads.
#
#   ./tools/check-blueprint-discovery.sh \
#       -f SITE/site/values/global.yaml \
#       -f SITE/site/values/identity.yaml               # assert, against a generated site
#
# THE NEGATIVE TEST IS THREE INVOCATIONS, not one: `--poison`, then the gate
# with no flag (which MUST exit 1), then `--unpoison`. `--poison` performs every
# step itself; before 2026-09-12 it did one of four and printed the rest, so
# running it and re-running the gate produced a pass that had tested nothing.
# VALUES FILES: pass -f (or --values) as many times as the install did, IN THE
# SAME ORDER, globals first and the layer's own file second, because later files
# win exactly as they do for helm and for the multi-source Applications the
# installer writes. A site generated by install/tockmox-install.sh has TWO files
# per layer, `site/values/global.yaml` and `site/values/<layer>.yaml`, and the
# layer's file alone fails the chart schema on `global.internalDomain` before
# this gate examines anything ... an error that reads as a site defect when the
# site is fine (TM-0362). With no -f, the legacy VALUES environment variable is
# honoured, colon-separated, defaulting to ci/values.yaml, which is NOT a site.
#
# NEEDS A LIVE CLUSTER with the identity layer installed. This is the one gate
# in tools/ that cannot run in CI, and that is the whole point of it.
#
# WHAT IT IS, stated so nobody has to run it to find out (TM-0320). This is a
# RELEASE gate, not a per-commit gate and not an operator convenience. It is
# wired into `RELEASING.md` and is asserted during the greenfield gate install;
# `docs/administration/identity.md` names it as "a live cluster only, never CI".
# `tests/executed-docs/INVENTORY.md` carries it as a row, which is where the
# question "what is covered, and by what" is actually answered.
#
# SO A RED RESULT FROM `for f in tools/check-*.sh` IS NOT A DEFECT.
# That sweep is the closing check of an ordinary working session, run in a
# sandbox with no cluster, and this gate cannot pass there ... ever. Reporting
# that as a failure alongside twelve real ones trains people to skim past red in
# this directory, which is the failure mode the whole tools/ suite exists to
# avoid. So the no-substrate path exits **2**, not 1, and says SKIPPED rather
# than FAIL:
#
#   exit 0  every expected blueprint present and successful
#   exit 1  a real defect ... missing, errored, or timed out
#   exit 2  could not run: no kubectl, no helm, or no cluster to talk to
#
# A caller that treats any non-zero as failure will still see red, which is why
# the sweep in the run sheet distinguishes 2. Nothing here weakens the gate: a
# reachable cluster still makes every assertion, and a timeout is still a
# failure.
#
# RUN IT FROM A TREE THAT MATCHES THE INSTALL. The expected set is rendered from
# THIS working tree and compared against what is running on the cluster
# `kubectl` currently points at. If the two are different revisions the mismatch
# is real and the failure is spurious, which is a confusing five minutes. Same
# for values: pass the site's own values files if the install used them, because
# a site can disable an app blueprint and then it is correctly absent.
#
# WHY A GATE, and why the obvious version of it does not work.
#
# CI parses every rendered blueprint as YAML. That proves they are well-formed
# and proves nothing else: a blueprint can parse perfectly and still reference a
# group, brand or application that a fresh install does not have. That failure
# only exists against a running, EMPTY Authentik, which is exactly the case the
# greenfield rule was written for. `identity.md` said the release gate asserted
# this long before anything did; the page was corrected 2026-08-22 and this
# script is what makes the stronger claim true.
#
# TRAP 1 ... A POISONED BLUEPRINT IS ABSENT, NOT ERRORED.
# One invalid blueprint blocks the discovery pass for ALL of them. The casualties
# do not show up as `status=error`; they do not show up at all. So the obvious
# assertion ... "every BlueprintInstance reports successful" ... passes happily
# over an empty table. This script therefore asserts the EXPECTED SET IS PRESENT
# first, and only then that each member succeeded. Absence is the primary
# failure mode, so absence is the primary check.
#
# TRAP 2 ... DISCOVERY RACES THE ROLLOUT.
# The startup `blueprints_discovery` task goes to the shared broker and can be
# picked up by an OLD-ReplicaSet worker that does not have the new ConfigMap
# mounted. It then "succeeds" having seen nothing. A gate that reads status once,
# immediately after install, can read that empty pass and go green. So this polls
# until every expected blueprint reaches a terminal state, and a TIMEOUT IS A
# FAILURE. A gate that gives up and passes is worse than no gate.
#
# TRAP 3 ... THE EXPECTED SET IS DERIVED, NEVER HARDCODED.
# A count baked into this file goes stale the first time a sixth blueprint ships,
# and it goes stale in the direction that passes. The expected names come out of
# the rendered ConfigMap every run.
#
# NO AUTHENTIK CREDENTIALS ARE USED OR NEEDED. Status is read with `ak shell`
# inside the worker, which is Django, not the API. That matters beyond
# convenience: it means this gate does NOT require a bootstrapped Authentik, so
# it does not compete with leaving the lab instance un-bootstrapped for the
# `/setup` screenshot. Those two were believed to contend for the same instance;
# they do not.
set -euo pipefail
cd "$(dirname "$0")/.."

# The NAMESPACE, which is not the chart name. `tockmox-identity` is the chart
# and the Helm release ... the workloads land in `namespaces.authentik`, which
# defaults to `tockmox-authentik`. The old default named the chart, so on a real
# install this gate found no such namespace and took its own not-installed
# branch: it printed
#
#   SKIPPED: namespace tockmox-identity is not present ... the identity layer
#            is not installed here
#
# against a cluster where the identity layer was installed, Synced and Healthy.
# Verified 2026-09-04: with the namespace corrected the same gate reports
# 5/5 blueprints present and successful. A gate that skips is not a gate, and
# this one announced its own blind spot as a reassurance ... override NS if your
# site renamed `namespaces.authentik`.
NS=${NS:-tockmox-authentik}
TIMEOUT=${TIMEOUT:-300}
INTERVAL=${INTERVAL:-10}
POISON=0
UNPOISON=0
POISON_CM="tockmox-blueprint-poison-test"
CONTEXT="${KUBE_CONTEXT:-}"
ASSUME_YES="${TOCKMOX_ASSUME_YES:-0}"

# Repeated -f, passed through to helm as repeated -f in the order given. An
# array, so a path with a space survives; bash 3.2 handles this form.
VALUES_FILES=()
while [ $# -gt 0 ]; do
  case "$1" in
    --poison) POISON=1; shift ;;
    --unpoison) UNPOISON=1; shift ;;
    --context)
      [ $# -ge 2 ] || { echo "usage: $1 needs a context name" >&2; exit 2; }
      CONTEXT="$2"; shift 2 ;;
    --yes|-y) ASSUME_YES=1; shift ;;
    -f|--values)
      [ $# -ge 2 ] || { echo "usage: $1 needs a file argument" >&2; exit 2; }
      VALUES_FILES+=("$2"); shift 2 ;;
    -h|--help) sed -n '4,20p' "$0"; exit 0 ;;
    *) echo "unknown argument: $1 (try --help)" >&2; exit 2 ;;
  esac
done
if [ ${#VALUES_FILES[@]} -eq 0 ]; then
  # Legacy form: VALUES=a.yaml:b.yaml. ci/values.yaml is the default and is a
  # CI fixture, not a site; the header says why that matters.
  IFS=':' read -r -a VALUES_FILES <<< "${VALUES:-ci/values.yaml}"
fi
HELM_VALUES=()
for f in "${VALUES_FILES[@]}"; do
  [ -f "$f" ] || { echo "values file not found: $f" >&2; exit 2; }
  HELM_VALUES+=(-f "$f")
done

# Every kubectl in this script goes through `kc`, so --context is impossible to
# forget on one call and lose the guarantee. bash 3.2 safe: an empty array under
# `set -u` needs the ${arr[@]+...} form (macOS ships 3.2, TM-0245).
KCTX=()
[ -n "$CONTEXT" ] && KCTX=(--context "$CONTEXT")
kc() { kubectl ${KCTX[@]+"${KCTX[@]}"} "$@"; }
# For the guidance strings this script prints, so a copied command carries the
# context too rather than silently resolving current-context on paste.
CTX_TEXT=""
[ -n "$CONTEXT" ] && CTX_TEXT="--context $CONTEXT "

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# exit 2, not 1. See the header: "could not run" and "found a defect" are
# different reports, and collapsing them is how a permanently-red gate teaches
# people to ignore this directory.
command -v kubectl >/dev/null || { echo "SKIPPED: kubectl not on PATH; this is a release gate and needs a live cluster"; exit 2; }
command -v helm    >/dev/null || { echo "SKIPPED: helm not on PATH; cannot render the expected set"; exit 2; }
kc config current-context >/dev/null 2>&1 || { echo "SKIPPED: no kubectl context to assert against (pass --context, or set one)"; exit 2; }
kc get ns "$NS" >/dev/null 2>&1 || { echo "SKIPPED: namespace $NS is not present on $(kc config current-context); the identity layer is not installed here"; exit 2; }

# `kubectl config current-context` REPORTS THE KUBECONFIG'S current-context and
# ignores --context entirely, so reading it through `kc` names the wrong cluster
# whenever --context is in play. Measured 2026-09-15: it printed the
# kubeconfig's default context on a run that was correctly acting on the context
# passed to --context ... which on that workstation meant a PRODUCTION name
# beside a lab server. The effective context is what --context said, when it
# said anything.
if [ -n "$CONTEXT" ]; then
  TARGET_CTX="$CONTEXT"
else
  TARGET_CTX="$(kubectl config current-context)"
fi
# A NAME CAN LIE. `rename-context` renames the context and leaves the cluster
# entry alone, and on a flatten-merge the first file wins ... a "lab" context
# that reached production is a recorded incident, which is why
# _gate-env asserts on the RESOLVED SERVER and never on the name. Print the
# server beside the name so the confirmation below is made against the thing
# that cannot be renamed.
TARGET_API="$(kc config view --minify -o jsonpath='{.clusters[0].cluster.server}' 2>/dev/null || true)"
echo "context: $TARGET_CTX${CONTEXT:+ (from --context)}"
echo "server:  ${TARGET_API:-<unresolved>}"
[ -n "$CONTEXT" ] || echo "         ^ RESOLVED FROM current-context; pass --context to say which cluster you mean"

# THE GUARD. Only the writing paths reach it.
if [ "$POISON" = 1 ] || [ "$UNPOISON" = 1 ]; then
  action=$([ "$POISON" = 1 ] && echo "POISON" || echo "UNPOISON")
  cat >&2 <<EOF

  $action will WRITE to this cluster:
    context   : $TARGET_CTX
    server    : ${TARGET_API:-<unresolved>}
    namespace : $NS
    creates/deletes ConfigMap $POISON_CM
    PATCHES the Authentik worker Deployment and waits for its rollout

EOF
  if [ "$ASSUME_YES" = 1 ]; then
    echo "  proceeding without confirmation (--yes / TOCKMOX_ASSUME_YES)" >&2
  elif [ -t 0 ]; then
    printf '  Type the context name to proceed: ' >&2
    read -r reply
    [ "$reply" = "$TARGET_CTX" ] || { echo "  refused: typed context did not match \"$TARGET_CTX\"" >&2; exit 2; }
  else
    echo "  REFUSED: not an interactive terminal and --yes was not given." >&2
    echo "  A destructive release step does not run unattended against an unnamed cluster." >&2
    exit 2
  fi
fi
echo "namespace: $NS"
echo "values: ${VALUES_FILES[*]}"

# ---------------------------------------------------------------------------
# 1. The expected set, from the rendered ConfigMap.
# ---------------------------------------------------------------------------
if ! helm template t charts/tockmox-identity "${HELM_VALUES[@]}" -n "$NS" \
     -s templates/sso-blueprints.yaml > "$tmp/bp.yaml" 2> "$tmp/render.err"; then
  cat "$tmp/render.err" >&2
  # The schema error above names a global.* key, which reads as a defect in
  # the site values. It usually is not: a generated site keeps global.* in
  # site/values/global.yaml, and that file was not passed. Say so.
  if [ ${#VALUES_FILES[@]} -eq 1 ] && grep -q 'global\.' "$tmp/render.err"; then
    echo "HINT: one values file was given and the render failed on a global.* key." >&2
    echo "      A generated site splits globals from the layer file. Pass both:" >&2
    echo "        -f SITE/site/values/global.yaml -f SITE/site/values/identity.yaml" >&2
  fi
  exit 2
fi

python3 - "$tmp/bp.yaml" "$tmp/expected.txt" <<'PY'
import sys, yaml, re
docs = [d for d in yaml.safe_load_all(open(sys.argv[1])) if d]
if not docs:
    print("FAIL: the blueprint ConfigMap did not render at all, so this gate is checking nothing")
    sys.exit(1)
data = docs[0].get('data') or {}
if not data:
    print("FAIL: the blueprint ConfigMap rendered with no blueprints in it, so this gate is checking nothing")
    sys.exit(1)
out = []
for filename, body in data.items():
    # metadata.name is what BlueprintInstance reports; fall back to the filename
    # stem, which is what Authentik uses when a blueprint declares no name.
    m = re.search(r'^metadata:\s*$(.*?)(?=^\S|\Z)', body, re.M | re.S)
    name = None
    if m:
        n = re.search(r'^\s+name:\s*(\S.*)$', m.group(1), re.M)
        if n:
            name = n.group(1).strip().strip('"\'')
    out.append((name or filename.rsplit('.', 1)[0], filename))
with open(sys.argv[2], 'w') as f:
    for name, filename in sorted(out):
        f.write(f"{name}\t{filename}\n")
print(f"expecting {len(out)} blueprint(s):")
for name, filename in sorted(out):
    print(f"  {name:32s} <- {filename}")
PY

EXPECTED_N=$(wc -l < "$tmp/expected.txt" | tr -d ' ')
if [ "$EXPECTED_N" -eq 0 ]; then
  echo "FAIL: no expected blueprints derived, which means this gate is checking nothing"
  exit 1
fi

# ---------------------------------------------------------------------------
# 2. Find the worker. By LABEL, never by name ... the release name is a site
#    choice and the deployment is <release>-authentik-worker.
# ---------------------------------------------------------------------------
WORKER=$(kc -n "$NS" get deploy \
  -l app.kubernetes.io/name=authentik,app.kubernetes.io/component=worker \
  -o jsonpath='{.items[0].metadata.name}' 2>/dev/null || true)
if [ -z "$WORKER" ]; then
  echo "FAIL: no authentik worker Deployment in namespace $NS."
  echo "      Looked for labels app.kubernetes.io/name=authentik,component=worker."
  echo "      If the identity layer is installed elsewhere, set NS."
  exit 1
fi
echo "worker: $WORKER"

# ---------------------------------------------------------------------------
# 3. Optionally poison, to prove the gate fails. THE NEGATIVE TEST.
#
#    Injected out-of-band rather than shipped behind a values flag, because that
#    is how a real bad blueprint arrives: someone adds a file that references
#    something a fresh install does not have. A test-only value would prove the
#    gate catches a case the product deliberately constructed, which is a weaker
#    claim and leaves scaffolding in the chart.
# ---------------------------------------------------------------------------
# POISON_CM is defined above, with the write guard that names it.
if [ "$POISON" -eq 1 ]; then
  echo
  echo "POISON MODE: injecting a blueprint that references a group no fresh install has."
  cat > "$tmp/poison.yaml" <<'BADBP'
version: 1
metadata:
  name: tockmox-poison-test
entries:
  - model: authentik_core.application
    identifiers:
      slug: tockmox-poison-test
    attrs:
      name: Poison Test
      group: !Find [authentik_core.group, [name, this-group-does-not-exist]]
BADBP
  kc -n "$NS" delete configmap "$POISON_CM" --ignore-not-found
  kc -n "$NS" create configmap "$POISON_CM" \
    --from-file=tockmox-poison-test.yaml="$tmp/poison.yaml"

  # ALL FOUR STEPS RUN HERE. Until 2026-09-12 this block created the ConfigMap
  # and then PRINTED the remaining three as instructions, which is a different
  # thing from doing them and reads identically at a glance. An operator
  # following the run sheet's negative-test row literally ran `--poison`, saw it
  # exit 0, re-ran the gate, got `5/5 present, 5 successful`, and had every
  # reason to record the negative test as passed ... having tested nothing. A
  # step that must happen by hand between two automated ones is a step that gets
  # skipped, and this one is skipped in the direction that looks like success.
  #
  # Skipping either of the middle two makes the gate PASS for reasons that have
  # nothing to do with the gate. Verified 2026-09-04: with only the ConfigMap
  # this script reports 5/5 successful and exits 0. That is not the gate being
  # decoration ... it is the poison never having reached Authentik.
  echo
  echo "  1/4 ConfigMap $POISON_CM created."

  # Strategic merge, not a JSON-patch append to `/spec/template/spec/volumes/-`.
  # The append form fails outright when the key is absent, and it duplicates the
  # entry when run twice. Merging BY NAME creates the list if it is missing and
  # is idempotent, so a half-finished poison run can simply be re-run.
  CONTAINER=$(kc -n "$NS" get deploy "$WORKER" \
    -o jsonpath='{.spec.template.spec.containers[0].name}')
  echo "  2/4 mounting it into container '$CONTAINER' (volume + volumeMount)."
  echo "      A volume with no mount never appears in the container, so the"
  echo "      blueprint would not be on disk to be found."
  kc -n "$NS" patch deploy "$WORKER" --type=strategic -p "{
    \"spec\": {\"template\": {\"spec\": {
      \"volumes\": [{\"name\": \"poison\", \"configMap\": {\"name\": \"$POISON_CM\"}}],
      \"containers\": [{\"name\": \"$CONTAINER\", \"volumeMounts\": [
        {\"name\": \"poison\", \"mountPath\": \"/blueprints/mounted/poison\"}]}]
    }}}
  }" >/dev/null

  echo "  3/4 waiting for the worker to roll."
  kc -n "$NS" rollout status "deploy/$WORKER" --timeout=180s

  # Authentik scans /blueprints on an interval, not on mount, so a file that is
  # present is not yet a blueprint it knows about. Without this the gate can be
  # re-run too early and report green against a poison that simply has not been
  # noticed yet ... a false pass with a race in it, which is worse than a plain
  # one because it is intermittent.
  echo "  4/4 triggering discovery, then WAITING for the row to appear."
  # `blueprints_discovery.send()` ENQUEUES a task; it does not perform one. The
  # first version of this block triggered and returned, and the poison was not
  # registered yet when the caller ran the gate a few seconds later ... so the
  # negative test read whatever the instance happened to say, which is the exact
  # unreliability this mode exists to remove. Measured on a single-node reference
  # cluster, 2026-09-12:
  # after the trigger the BlueprintInstance did not exist; a second pass ~20s
  # later registered it as `error`.
  #
  # So poll for the ARTEFACT rather than trusting the trigger, and fail loudly
  # if it never lands. A --poison that returns success without the poison in
  # place is worse than no --poison at all.
  POISON_BP="tockmox-poison-test"
  poison_registered() {
    kc -n "$NS" exec "deploy/$WORKER" -i -- ak shell -c "
from authentik.blueprints.models import BlueprintInstance
print('TOCKMOX_POISON=' + ('yes' if BlueprintInstance.objects.filter(name='${POISON_BP}').exists() else 'no'))
" 2>/dev/null | grep -q 'TOCKMOX_POISON=yes'
  }

  deadline=$(( $(date +%s) + ${TOCKMOX_POISON_TIMEOUT:-180} ))
  registered=0
  while [ "$(date +%s)" -lt "$deadline" ]; do
    kc -n "$NS" exec "deploy/$WORKER" -- ak shell -c \
      'from authentik.blueprints.v1.tasks import blueprints_discovery; blueprints_discovery.send()' \
      >/dev/null 2>&1 || true
    sleep 10
    if poison_registered; then registered=1; break; fi
    echo "      not registered yet; re-triggering."
  done

  if [ "$registered" -ne 1 ]; then
    echo "FAIL: the poison is mounted but never registered as a BlueprintInstance"
    echo "      within $(( ${TOCKMOX_POISON_TIMEOUT:-180} )) seconds. The negative test"
    echo "      CANNOT be run in this state ... a gate result now says nothing about"
    echo "      whether the gate works. Do not record N9 either way."
    echo "      Undo with: $0 --unpoison"
    exit 1
  fi
  echo "      registered."

  echo
  echo "  POISONED. Now re-run this script WITHOUT --poison."
  echo "  THE GATE MUST THEN EXIT 1. If it exits 0, the gate is decoration."
  echo "  Whatever the result, undo it:  $0 --unpoison"
  exit 0
fi

# ---------------------------------------------------------------------------
# 3b. Reverse the poison. Separate flag rather than a trap, because the whole
#     point is that the cluster stays poisoned across a SECOND invocation of
#     this script ... a trap that cleaned up on exit would remove the poison
#     before the assertion run ever saw it.
# ---------------------------------------------------------------------------
if [ "${UNPOISON:-0}" -eq 1 ]; then
  echo
  echo "UNPOISON: removing the test blueprint and its mount."
  CONTAINER=$(kc -n "$NS" get deploy "$WORKER" \
    -o jsonpath='{.spec.template.spec.containers[0].name}')
  # `$patch: delete` removes an element by its list's MERGE KEY, and the two
  # lists do not share one: `volumes` merges on `name`, `volumeMounts` merges on
  # `mountPath`. Keying the mount on `name` is rejected outright with
  #   does not contain declared merge key: mountPath
  # ... measured 2026-09-12, on the first real run of this mode against a live
  # Authentik.
  # Removing by INDEX would work for both and is what breaks as soon as anything
  # else has been added to either list, so the merge keys are the right lever
  # and each list needs its own.
  kc -n "$NS" patch deploy "$WORKER" --type=strategic -p "{
    \"spec\": {\"template\": {\"spec\": {
      \"volumes\": [{\"name\": \"poison\", \"\$patch\": \"delete\"}],
      \"containers\": [{\"name\": \"$CONTAINER\", \"volumeMounts\": [
        {\"mountPath\": \"/blueprints/mounted/poison\", \"\$patch\": \"delete\"}]}]
    }}}
  }" >/dev/null
  kc -n "$NS" rollout status "deploy/$WORKER" --timeout=180s
  kc -n "$NS" delete configmap "$POISON_CM" --ignore-not-found

  # THE ROW OUTLIVES THE FILE, and re-running discovery does not reap it.
  # Measured 2026-09-12 on a live instance: with the volume, the mount and the
  # ConfigMap all gone, `BlueprintInstance` still held `tockmox-poison-test` in
  # `error`. Since this gate fails on ANY instance in error, an --unpoison that
  # stopped at the file would leave the gate permanently red and the operator
  # hunting a blueprint that no longer exists anywhere on disk. Delete the row.
  kc -n "$NS" exec "deploy/$WORKER" -i -- ak shell -c "
from authentik.blueprints.models import BlueprintInstance
n, _ = BlueprintInstance.objects.filter(name='tockmox-poison-test').delete()
print('deleted rows:', n)
" >/dev/null 2>&1 || {
    echo "WARNING: could not delete the tockmox-poison-test BlueprintInstance row."
    echo "         The files are gone but the row remains, so the gate will stay RED."
    echo "         Remove it by hand before reading any gate result:"
    echo "           kubectl -n $NS exec deploy/$WORKER -- ak shell -c \\"
    echo "             \"from authentik.blueprints.models import BlueprintInstance; BlueprintInstance.objects.filter(name='tockmox-poison-test').delete()\""
    exit 1
  }

  kc -n "$NS" exec "deploy/$WORKER" -- ak shell -c \
    'from authentik.blueprints.v1.tasks import blueprints_discovery; blueprints_discovery.send()' \
    >/dev/null 2>&1 || true

  # Assert the artefact rather than the exit code of the delete.
  if kc -n "$NS" exec "deploy/$WORKER" -i -- ak shell -c "
from authentik.blueprints.models import BlueprintInstance
print('TOCKMOX_LEFT=' + str(BlueprintInstance.objects.filter(name='tockmox-poison-test').count()))
" 2>/dev/null | grep -q 'TOCKMOX_LEFT=0'; then
    echo "  clean ... files removed and the BlueprintInstance row is gone."
    echo "  Re-run without a flag; the gate should return to its pre-poison result."
  else
    echo "FAIL: the poison row is still present after deletion. The gate will stay RED."
    exit 1
  fi
  exit 0
fi

# ---------------------------------------------------------------------------
# 4. Poll discovery status. Timeout FAILS.
# ---------------------------------------------------------------------------
read_status() {
  kc -n "$NS" exec "deploy/$WORKER" -i -- ak shell -c '
import json
from authentik.blueprints.models import BlueprintInstance
print("TOCKMOX_JSON_BEGIN")
print(json.dumps([
    {"name": b.name, "path": b.path, "status": str(b.status)}
    for b in BlueprintInstance.objects.all()
]))
print("TOCKMOX_JSON_END")
' 2>/dev/null | sed -n '/TOCKMOX_JSON_BEGIN/,/TOCKMOX_JSON_END/p' | sed '1d;$d'
}

echo
deadline=$(( $(date +%s) + TIMEOUT ))
while :; do
  read_status > "$tmp/actual.json" 2>/dev/null || true
  if [ -s "$tmp/actual.json" ]; then
    if python3 - "$tmp/expected.txt" "$tmp/actual.json" quiet <<'PY'
