"""Write the default Platform Management catalog into its documentation page (TM-1112).

The catalog (tockmox-ui/app/platform_catalog.yaml) is data the UI reads; the page's table of roles is
generated from it, so the two cannot drift. Only the block between the two markers is written.

  python3 tools/gen-platform-catalog-doc.py           rewrite the block
  python3 tools/gen-platform-catalog-doc.py --check   exit 1 if the block is stale (run by check-all.sh)
"""
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOG = os.path.join(ROOT, "tockmox-ui", "app", "platform_catalog.yaml")
PAGE = os.path.join(ROOT, "docs", "administration", "platform-management.md")
BEGIN = "<!-- BEGIN generated by tools/gen-platform-catalog-doc.py: do not edit by hand -->"
END = "<!-- END generated -->"
MODES = {"observe": "Observe", "propose": "Propose", "act": "Act"}


def cell(s):
    return " ".join(str(s).split()).replace("|", "\\|")


def table(doc):
    out = []
    for t in doc["teams"]:
        out.append(f"**{cell(t['name'])}.** {cell(t.get('purpose', ''))}")
        out.append("")
        out.append("| Role | Mode | ITIL 4 practice | Owns scheduled work matching | Watches |")
        out.append("|---|---|---|---|---|")
        for a in [t["lead"]] + list(t.get("members") or []):
            name = cell(a["name"]) + (" (lead)" if a is t["lead"] else "")
            itil = cell((a.get("reference") or {}).get("itil", ""))
            sch = a.get("schedules") or {}
            match = ", ".join(f"`{p}`" for p in (sch.get("match") or [])) or "none yet"
            planned = len(sch.get("planned") or [])
            if planned:
                match += f"; {planned} planned"
            watches = ", ".join(cell(s.get("label", s.get("id", ""))) for s in (a.get("signals") or [])) or "none yet"
            out.append(f"| {name} | {MODES.get(a.get('mode', 'observe'), a.get('mode'))} | {itil} | {match} | {watches} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def render(page_text, doc):
    if page_text.count(BEGIN) != 1 or page_text.count(END) != 1:
        sys.exit(f"{os.path.relpath(PAGE, ROOT)}: needs exactly one BEGIN and one END marker")
    head, rest = page_text.split(BEGIN)
    _, tail = rest.split(END)
    return head + BEGIN + "\n\n" + table(doc) + "\n" + END + tail


def main():
    doc = yaml.safe_load(open(CATALOG, encoding="utf-8"))
    cur = open(PAGE, encoding="utf-8").read()
    new = render(cur, doc)
    if "--check" in sys.argv[1:]:
        if new != cur:
            print(f"{os.path.relpath(PAGE, ROOT)} is STALE: run tools/gen-platform-catalog-doc.py")
            return 1
        print(f"{os.path.relpath(PAGE, ROOT)} matches the catalog")
        return 0
    if new != cur:
        open(PAGE, "w", encoding="utf-8").write(new)
        print(f"wrote {os.path.relpath(PAGE, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
