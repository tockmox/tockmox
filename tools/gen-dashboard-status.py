"""Generates the Tockmox / Status board (uid tockmox-status) from tockmox-ui/app/panels.yaml.

The Tockmox UI draws its trend panels from panels.yaml and links each one here, so the console and the board read
the SAME expressions: change panels.yaml, run this, commit both. One timeseries panel per UI panel, in file order,
grouped by the page that shows it; panel ids follow that order, which is what the UI's ?viewPanel= links use.
Drawer panels (page: part) are per part and templated by namespace, so they are not on the board.

    python3 tools/gen-dashboard-status.py            write charts/tockmox-observability/dashboards/status.json
    python3 tools/gen-dashboard-status.py --check    exit 1 if the committed JSON is not what this file generates

ABSENCE IS NOT GREEN here as in the UI: "no data" is shown as such, never drawn as zero.
"""
import json
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tockmox-ui", "app", "panels.yaml")
OUT = os.path.join(ROOT, "charts", "tockmox-observability", "dashboards", "status.json")
DS = {"type": "prometheus", "uid": "${datasource}"}
UNIT = {"percent": "percent", "count": "short", "days": "d", "seconds": "s", "usd": "currencyUSD", "ratio": "percentunit"}
ROWS = {"status": "Status: the last 24 hours", "ai-nodes": "AI: inference nodes", "ai-models": "AI: the model gateway",
        "platform": "Platform"}


def thresholds(p):
    green, amber, red = "green", "orange", "red"
    warn, crit = p.get("warn"), p.get("crit")
    if warn is None and crit is None:
        return {"mode": "absolute", "steps": [{"color": "#6FB3DD", "value": None}]}
    if p.get("below"):
        steps = [{"color": red, "value": None}]
        if crit is not None:
            steps.append({"color": amber if warn is not None else green, "value": crit})
        if warn is not None:
            steps.append({"color": green, "value": warn})
        return {"mode": "absolute", "steps": steps}
    steps = [{"color": green, "value": None}]
    if warn is not None:
        steps.append({"color": amber, "value": warn})
    if crit is not None and crit != warn:
        steps.append({"color": red, "value": crit})
    return {"mode": "absolute", "steps": steps}


def main():
    with open(SRC, encoding="utf-8") as fh:
        doc = yaml.safe_load(fh)
    panels, y, pid = [], 0, 0
    board_panels = [p for p in doc["panels"] if p["page"] != "part"]
    pages = [pg for pg in ROWS if any(p["page"] == pg for p in board_panels)]
    # ids first, in file order, so the UI's ?viewPanel=<n> (its 1-based position) lands on the right panel
    ids = {p["id"]: i + 1 for i, p in enumerate(board_panels)}
    next_row = len(board_panels) + 1
    for pg in pages:
        panels.append({"id": next_row, "type": "row", "title": ROWS[pg], "collapsed": False,
                       "gridPos": {"x": 0, "y": y, "w": 24, "h": 1}, "panels": []})
        next_row += 1
        y += 1
        x = 0
        for p in [p for p in board_panels if p["page"] == pg]:
            if x + 8 > 24:
                x, y = 0, y + 7
            legend = "{{" + p["legend"] + "}}" if p.get("legend") else p["title"]
            panels.append({
                "id": ids[p["id"]], "type": "timeseries", "title": p["title"], "description": p["describe"],
                "datasource": DS, "gridPos": {"x": x, "y": y, "w": 8, "h": 7},
                "targets": [{"datasource": DS, "expr": p["expr"].strip(), "refId": "A", "legendFormat": legend,
                             "interval": p["step"]}],
                "fieldConfig": {"defaults": {"unit": UNIT[p["unit"]], "thresholds": thresholds(p), "noValue": "no data",
                                             "custom": {"thresholdsStyle": {"mode": "dashed"}, "spanNulls": False,
                                                        "lineWidth": 2, "fillOpacity": 8}},
                                "overrides": []},
                "options": {"legend": {"displayMode": "list", "placement": "bottom", "showLegend": bool(p.get("legend"))},
                            "tooltip": {"mode": "multi", "sort": "desc"}},
            })
            x += 8
        y += 7
    board = {
        "uid": "tockmox-status", "title": "Tockmox / Status",
        "description": "The trends the Tockmox UI draws on Status, AI and Platform, from the same expressions "
                       "(tockmox-ui/app/panels.yaml). Generated by tools/gen-dashboard-status.py; do not edit.",
        "tags": ["tockmox", "product", "tier-l1", "ui"],
        "editable": False, "graphTooltip": 1, "refresh": "1m", "schemaVersion": 39,
        "time": {"from": "now-24h", "to": "now"},
        "links": [{"asDropdown": True, "icon": "external link", "includeVars": False, "keepTime": True, "tags": ["tockmox"],
                   "targetBlank": False, "title": "Tockmox dashboards", "type": "dashboards"}],
        "templating": {"list": [{"current": {"text": "Prometheus", "value": "Prometheus"}, "hide": 0, "label": "Data source",
                                 "name": "datasource", "query": "prometheus", "type": "datasource"}]},
        "panels": panels,
    }
    text = json.dumps(board, indent=2) + "\n"
    if "--check" in sys.argv:
        try:
            with open(OUT, encoding="utf-8") as fh:
                same = fh.read() == text
        except FileNotFoundError:
            same = False
        print("status.json is " + ("current" if same else "STALE: run tools/gen-dashboard-status.py"))
        return 0 if same else 1
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote", os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
