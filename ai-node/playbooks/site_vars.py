"""Turn a node's two site files into the one extra-vars file the playbook is given.

    site_vars.py AI_NODE_YAML DESIRED_YAML OUT_YAML

The site files are data from a repository that may not have been verified (signing mode warn), so
they must never become top-level Ansible variables: extra-vars beat role defaults and play vars, and
a key such as ``firewall_pfctl`` would then choose which program a root task runs. They are written
under one name instead, ``tn_site``, as ``tn_site.ai_node`` and ``tn_site.desired``, and every role
reads them only from there.

The whole structure is tagged ``!unsafe``, so Ansible never evaluates a string in it as a template
(without the tag, a value such as ``{{ lookup('pipe', ...) }}`` in a free-text field would run).

Needs PyYAML (Homebrew's ansible python has it). Exit 0 and the file written, or exit 2 with the reason
on stderr and nothing written.
"""
import os
import sys

import yaml


def load(path):
    with open(path, encoding="utf-8") as f:
        doc = yaml.safe_load(f)
    if not isinstance(doc, dict):
        raise ValueError("%s is not a YAML mapping" % os.path.basename(path))
    return doc


def render(ai_node, desired):
    body = yaml.safe_dump({"ai_node": ai_node, "desired": desired}, default_flow_style=False,
                          sort_keys=True, allow_unicode=True)
    return "# Generated by site_vars.py for one converge. Site data, namespaced and unsafe.\n" \
           "tn_site: !unsafe\n" + "".join("  " + line if line.strip() else line for line in body.splitlines(True))


def main(argv):
    if len(argv) != 4:
        sys.stderr.write(__doc__)
        return 64
    try:
        text = render(load(argv[1]), load(argv[2]))
    except (OSError, ValueError, yaml.YAMLError) as e:
        sys.stderr.write("site_vars: %s\n" % e)
        return 2
    tmp = argv[3] + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, argv[3])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
