def render(site: Site, ai_node_id: str, *, validate: bool = True) -> tuple[str, dict]:
    """Render one enrolled node. Returns (the text of desired.yaml, the desired dict). Raises AiNodeError naming the
    invariant that fired, SchemaUnavailable when validate is on and jsonschema is missing."""
    if site.values_error:
        raise site.values_error
    en = site.enrollments.get(ai_node_id)
    where = f"{AI_NODES_DIR}/{ai_node_id}/{AUTHORED}"
    if en is None or en.orphan:
        known = site.inventory.node(ai_node_id) is not None
        raise AiNodeError(("not-enrolled",
                           f"{where} does not exist, so {ai_node_id!r} is not an enrolled AI node. "
                           + ("It is registered in inferenceNodes and stays unmanaged; to have Tockmox converge it, add the "
                              "file (python -m app.ai_nodes skeleton prints one)." if known else
                              "It is not in inferenceNodes either.")), node=ai_node_id)
    if en.error:
        raise en.error
    doc = en.doc
    if validate:
        _check_schema(doc, "ai-node.v1.schema.json", where, "schema")
    if doc.get("aiNodeId") != ai_node_id:
        raise AiNodeError(("id-mismatch", f"{where} says aiNodeId {doc.get('aiNodeId')!r} but its directory is "
                           f"{ai_node_id!r}; they must be the same string"), node=ai_node_id)
    if not isinstance(doc.get("aiNodeId"), str) or not ID_RE.match(doc["aiNodeId"]):
        raise AiNodeError(("schema", f"{where}: aiNodeId must match {ID_RE.pattern}"), node=ai_node_id)
    inv_node = site.inventory.node(ai_node_id)
    if inv_node is not None and not inv_node.enrolled:
        raise AiNodeError(("inventory-not-enrolled",
                           f"{where} exists but inferenceNodes node {ai_node_id!r} does not carry management: "
                           "{enrolled: true}. Set it in the same change, so the UI expects this node's convergence "
                           "and readiness (an enrolled node that never reports reads Unknown, never healthy)."),
                          node=ai_node_id)
    desired = derive(site, ai_node_id, doc)
    if validate:
        _check_schema(desired, "desired.v1.schema.json", f"{AI_NODES_DIR}/{ai_node_id}/{GENERATED} (rendered)",
                      "desired-schema")
    return dump_desired(desired, site.values_path), desired


@dataclass
class Result:
    ai_node_id: str
    status: str            # OK | STALE | INVALID
    reason: str

    def line(self) -> str:
        return f"{self.status:<8}{self.ai_node_id}  {self.reason}"


def _first_diff(a: str, b: str) -> str:
    """Where two texts first differ, as a short window around the first differing character of the first
    differing line (the lines of a model entry are long, so the start of the line says nothing)."""
    al, bl = a.splitlines(), b.splitlines()
    for i in range(max(len(al), len(bl))):
        x = al[i] if i < len(al) else "(end of file)"
        y = bl[i] if i < len(bl) else "(end of file)"
        if x != y:
            k = next((j for j in range(min(len(x), len(y))) if x[j] != y[j]), min(len(x), len(y)))
            lo = max(0, k - 20)
            return f"line {i + 1} column {k + 1}: committed {x[lo:k + 20]!r}, rendered {y[lo:k + 20]!r}"
    return "trailing whitespace or line endings differ"


def check(site_root, values_path: str = DEFAULT_VALUES, site: Site | None = None) -> list[Result]:
    """Render every enrolled node to memory and compare byte for byte with the committed desired.yaml."""
    site = site or load_site(site_root, values_path)
    out = []
    for nid in enrolled_ids(site):
        en = site.enrollments[nid]
        if en.orphan:
            out.append(Result(nid, "STALE", f"{GENERATED} exists but {AUTHORED} does not (orphan): delete the "
                              "directory if the node is retired, or restore ai-node.yaml"))
            continue
        try:
            text, desired = render(site, nid)
        except AiNodeError as e:
            out.append(Result(nid, "INVALID", e.one_line()))
            continue
        if not en.generated_path.is_file():
            out.append(Result(nid, "STALE", f"{GENERATED} is missing: run render --write"))
            continue
        committed = en.generated_path.read_bytes().decode("utf-8", errors="replace")
        if committed == text:
            out.append(Result(nid, "OK", f"{GENERATED} is current (inputsSha256 {desired['inputsSha256'][:12]})"))
            continue
        m = re.search(r"^inputsSha256: ([0-9a-f]{64})$", committed, re.M)
        if m and m.group(1) == desired["inputsSha256"]:
            why = f"hand-edited: inputs unchanged ({m.group(1)[:12]}) but content differs, {_first_diff(committed, text)}"
        else:
            why = (f"inputs changed since it was rendered (committed {m.group(1)[:12] if m else 'none'}, now "
                   f"{desired['inputsSha256'][:12]}): run render --write; first difference {_first_diff(committed, text)}")
        out.append(Result(nid, "STALE", why))
    out += _fleet_agreement(site)
    return out


def _fleet_agreement(site: Site) -> list[Result]:
    """ai-nodes/fleet.yaml (what the converger pins) and inferenceNodes.aiNodes.toolkitRef (what the UI's bootstrap
    one-liner offers) name the same toolkit ref, so a node is never bootstrapped at one ref and converged at another."""
    fleet_path = site.root / AI_NODES_DIR / "fleet.yaml"
    ui_ref = getattr(getattr(site.inventory, "ai", None), "toolkit_ref", "") if site.inventory else ""
    if not fleet_path.is_file() or not ui_ref:
        return []
    try:
        fleet = yaml.safe_load(fleet_path.read_text(encoding="utf-8")) or {}
    except yaml.YAMLError as e:
        return [Result("fleet", "INVALID", f"{AI_NODES_DIR}/fleet.yaml does not parse: {e}")]
    ref = str(((fleet.get("toolkit") or {}) if isinstance(fleet, dict) else {}).get("ref") or "")
    if ref != ui_ref:
        return [Result("fleet", "INVALID", f"fleet-ref-mismatch: {AI_NODES_DIR}/fleet.yaml pins toolkit ref {ref!r} but "
                       f"inferenceNodes.aiNodes.toolkitRef is {ui_ref!r}; set both to the same release tag")]
    return []


def write_desired(site: Site, ai_node_id: str, text: str) -> bool:
    """Atomically write desired.yaml. True when the file changed."""
    p = site.enrollments[ai_node_id].generated_path
    data = text.encode("utf-8")
    if p.is_file() and p.read_bytes() == data:
        return False
    tmp = p.with_name(p.name + ".tmp")
    tmp.write_bytes(data)
    os.replace(tmp, p)
    return True


