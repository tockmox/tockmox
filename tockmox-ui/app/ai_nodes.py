"""The ai-node renderer: site values + an authored ai-node.yaml -> a generated desired.yaml.

An AI node is an inference host that Tockmox CONVERGES (the `ai-node/` toolkit), as opposed to one it only
registers and probes (app/nodes.py). Two files per node live in the adopter's site repository, outside every
Argo CD path:

  ai-nodes/<id>/ai-node.yaml   AUTHORED  what cannot be derived: OS posture, access, wired limit, engine versions
  ai-nodes/<id>/desired.yaml   GENERATED what is derived: engine instances, models at pinned revisions, firewall

desired.yaml is a PURE FUNCTION of (the node and its routes in `inferenceNodes`, the `modelLifecycle` catalog
joined on `model`, `inferenceNodes.gateway`'s CIDRs, ai-node.yaml). Nothing is mirrored by hand: one change to
site/values/models.yaml moves the gateway route, the engine instance, the firewall port and the model download
together, and `check` fails CI when the committed file is not what the inputs render.

This module reuses, and does not duplicate, the parse of app/nodes.py (inventory, ENGINES, the `-next` rule in
gateway_routes) and app/models.py (the catalog). It writes nothing but desired.yaml, and only under --write;
app/pr_opener.py keeps ownership of the whole of site/values/models.yaml.

  python -m app.ai_nodes render --site PATH [--values REL] [--ai-node ID ...] [--write]
  python -m app.ai_nodes check  --site PATH [--values REL]
  python -m app.ai_nodes skeleton --id ID --type TYPE [--memory-gib N] [--admin-cidr CIDR ...]

`check` prints one line per enrolled node, OK, STALE or INVALID with the reason, and exits 1 on any STALE or
INVALID. Exit 2 means the check could not run (no site, no jsonschema). Only ENROLLED nodes (those with an
ai-node.yaml) are rendered; an inferenceNodes node with none is registered but unmanaged and is left alone,
whatever its catalog entries look like.

INPUTS, EXACTLY (inputsSha256 = SHA-256 of canonical JSON: sorted keys, no whitespace, ASCII):
  aiNode   the authored ai-node.yaml, as loaded
  gateway  {sourceCidrs, scrapeCidrs}, normalised and sorted
  node     {id, type, metrics, endpoints: [{id, engine, url, authSecret}]}
  routes   [{alias, endpoint, model, contextTokens}]                    this node's routes, by alias
  catalog  [{id, model, stage, source: {kind, ref, revision}}]          the entries those routes join to, by model
Only the fields the output depends on are hashed, so a watcher noting `pending` on a catalog entry, or an
operator editing a route's `keep_alive`, does not make desired.yaml stale for no reason.

What is not certified here: the invariants below are the renderer's reading of the contract in
ai-node/README.md; that a converger applies desired.yaml correctly is the toolkit's tests' claim, not this
module's.
"""
