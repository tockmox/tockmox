def default_ai_node_doc(ai_node_id: str, node_type: str, memory_gib: float | None, admin_cidrs: list[str]) -> dict:
    """The skeleton as data (what skeleton_ai_node_yaml's text loads to)."""
    fam = TYPE_OS.get(node_type)
    if fam is None:
        raise AiNodeError(("skeleton", f"unknown node type {node_type!r}; one of {sorted(TYPE_OS)}"))
    fam = "macos" if fam == "any" and node_type == "apple-silicon-mac" else ("linux" if fam == "any" else fam)
    if not ID_RE.match(ai_node_id or "") or len(ai_node_id) > 40:
        raise AiNodeError(("skeleton", f"aiNodeId {ai_node_id!r} must match {ID_RE.pattern} and be at most 40 characters"))
    cidrs = _cidrs(list(admin_cidrs or []), "admin_cidrs")
    d = copy.deepcopy(DEFAULTS)
    doc = {"schema": AI_NODE_SCHEMA_ID, "aiNodeId": ai_node_id}
    doc["os"] = ({"family": "macos", **d["os"]} if fam == "macos" else {"family": "linux"})
    doc["power"] = d["power"]
    doc["access"] = {"adminCidrs": cidrs, **d["access"]}
    doc["accounts"] = d["accounts"]
    doc["labels"] = d["labels"]
    doc["paths"] = d["paths"]
    if fam == "macos" and memory_gib:
        doc["gpu"] = {"wiredLimitMiB": suggest_wired_limit_mib(float(memory_gib))}
    engines = {k: v for k, v in d["engines"].items() if fam == "macos" or k != "mlx-lm"}
    doc["engines"] = engines
    doc["models"] = d["models"]
    doc["strip"] = d["strip"]
    doc["updates"] = d["updates"]
    doc["telemetry"] = ({k: v for k, v in d["telemetry"].items()} if fam == "macos"
                        else {"nodeExporterPort": d["telemetry"]["nodeExporterPort"]})
    doc["legacy"] = None
    return doc


def _q(s: str) -> str:
    return json.dumps(s)


def skeleton_ai_node_yaml(ai_node_id: str, node_type: str, memory_gib: float | None, admin_cidrs: list[str]) -> str:
    """The authored-file skeleton the UI's Add node flow offers: every contract default written out, with comments.

    macOS: wiredLimitMiB is 87.5% of memory_gib, clamped into the range the role asserts and rounded down to a whole
    GiB, and FileVault is "off". When memory is unknown the wiredLimitMiB line is left as a comment and the file does
    not validate until a person sets it: a plausible number would be worse than a refusal."""
    doc = default_ai_node_doc(ai_node_id, node_type, memory_gib, admin_cidrs)
    mac = doc["os"]["family"] == "macos"
    cidrs = ", ".join(doc["access"]["adminCidrs"])

    def c(code: str, note: str = "") -> str:
        return f"{code:<34}# {note}" if note and len(code) < 34 else (f"{code}  # {note}" if note else code)

    L = [
        "# SPDX-License-Identifier: Apache-2.0",
        f"# ai-nodes/{ai_node_id}/ai-node.yaml: the AUTHORED half of this AI node's desired state.",
        "# desired.yaml beside it is GENERATED (python -m app.ai_nodes render --write); never edit that one.",
        "# Which engines run and which models they serve is NOT here: it comes from site/values/models.yaml.",
        "# Quote \"off\" and \"on\": unquoted they are booleans to some YAML loaders, and the renderer refuses them.",
        f"schema: {AI_NODE_SCHEMA_ID}",
        c(f"aiNodeId: {ai_node_id}", "must equal this directory and an inferenceNodes node id"),
        "os:",
    ]
    if mac:
        L += [
            "  family: macos",
            c(f"  minVersion: {_q(doc['os']['minVersion'])}", "lowest allowed OS version; a quoted string"),
            c("  expectedBuild: null", "optional, e.g. \"26A434\"; drift is reported, never enforced"),
            c("  filevault: \"off\"", "\"off\" | \"on_ssh_unlock\". off suits a lights-out machine on a UPS;"),
            "                                  # on_ssh_unlock needs a person to unlock the disk over SSH after a restart",
        ]
    else:
        L += ["  family: linux"]
    L += [
        "power:",
        "  preventSleep: true",
        c("  autoRestart: true", "'Start up when power is connected' is a console checklist item"),
        "access:",
        c(f"  adminCidrs: [{cidrs}]", "REQUIRED: port 22 (and 5900) are open to these; an empty list is refused"),
        c(f"  sshAllowUsers: [{', '.join(doc['access']['sshAllowUsers'])}]", "replace 'admin' with the break-glass account"),
        c("  screenSharing: false", "true also opens and admits port 5900"),
        "accounts:",
        c(f"  converge: {doc['accounts']['converge']}", "admin group, passwordless sudo, runs the converge daemon"),
        c(f"  service: {doc['accounts']['service']}", "hidden standard user that runs every engine and exporter"),
        "labels:",
        c(f"  prefix: {doc['labels']['prefix']}", "services are <prefix>.<service>; an adopted node keeps its old prefix"),
        "paths:",
        f"  root: {doc['paths']['root']}",
    ]
    if mac:
        L += ["gpu:"]
        if "gpu" in doc:
            v = doc["gpu"]["wiredLimitMiB"]
            lo, hi = wired_limit_bounds_mib(float(memory_gib))
            L += [c(f"  wiredLimitMiB: {v}", f"87.5% of {memory_gib:g} GiB, kept inside {lo}..{hi} (RAM/2 .. RAM - max(10 GiB, 10%))")]
        else:
            L += ["  # wiredLimitMiB: SET THIS. The node's memory is not recorded, so no number is proposed.",
                  "  # 87.5% of RAM is the usual choice; the role asserts RAM/2 <= value <= RAM - max(10 GiB, 10% of RAM)."]
    L += [c("engines:", "versions and arguments only")]
    if mac:
        e = doc["engines"]["mlx-lm"]
        L += ["  mlx-lm:",
              f"    version: {_q(e['version'])}",
              f"    python: {_q(e['python'])}",
              "    extraArgs: []"]
    L += ["  llama-server:",
          f"    brewFormula: {doc['engines']['llama-server']['brewFormula']}",
          "    extraArgs: []",
          "  ollama:",
          c("    env: {}", "e.g. OLLAMA_NUM_PARALLEL: \"2\" (quote the values)"),
          "models:",
          "  retain:",
          c(f"    keepUnreferencedDays: {doc['models']['retain']['keepUnreferencedDays']}",
            "a model that leaves modelsPresent stays this long, then goes")]
    if mac:
        L += [c("strip:", "\"off\" = the toolkit turns the feature off on this headless machine"),
              "  spotlight: \"off\"",
              "  timeMachine: \"off\"",
              "  analytics: \"off\"",
              "  siri: \"off\""]
    L += ["updates:",
          c("  autoInstall: false", "detect and alert; no enforcement without device management"),
          c("telemetry:", "must agree with inferenceNodes.nodes[].metrics when that is set"),
          f"  nodeExporterPort: {doc['telemetry']['nodeExporterPort']}"]
    if mac:
        L += [f"  macmonPort: {doc['telemetry']['macmonPort']}"]
    L += [c("legacy: null", "adopt-in-place only: {root: ..., serviceUser: ..., holdEngineSettings: true}"), ""]
    return "\n".join(L)


# ---------------------------------------------------------------- CLI

def _cli_site(args) -> Site:
    try:
        return load_site(args.site, args.values)
    except AiNodeError as e:
        print(f"ai_nodes: {e.one_line()}", file=sys.stderr)
        raise SystemExit(2)


def _cmd_check(args) -> int:
    site = _cli_site(args)
    try:
        results = check(args.site, args.values, site=site)
    except SchemaUnavailable as e:
        print(f"ai_nodes: cannot check: {e}", file=sys.stderr)
        return 2
    if site.values_error and not results:
        print(f"INVALID {args.values}  {site.values_error.one_line()}")
        return 1
    if not results:
        print(f"NONE    no enrolled AI nodes: no {AI_NODES_DIR}/<id>/{AUTHORED} under {args.site}")
        return 0
    for r in results:
        print(r.line())
    return 0 if all(r.status == "OK" for r in results) else 1


def _cmd_render(args) -> int:
    site = _cli_site(args)
    ids = args.ai_node or enrolled_ids(site)
    if not ids:
        print(f"ai_nodes: no enrolled AI nodes under {args.site}/{AI_NODES_DIR}", file=sys.stderr)
        return 1
    rc = 0
    for nid in ids:
        try:
            text, _ = render(site, nid)
        except AiNodeError as e:
            print(f"INVALID {nid}  {e.one_line()}", file=sys.stderr)
            rc = 1
            continue
        except SchemaUnavailable as e:
            print(f"ai_nodes: cannot render: {e}", file=sys.stderr)
            return 2
        if args.write:
            changed = write_desired(site, nid, text)
            print(f"{'WROTE' if changed else 'UNCHANGED'} {site.rel(site.enrollments[nid].generated_path)}")
        else:
            if len(ids) > 1:
                print(f"# ==> {AI_NODES_DIR}/{nid}/{GENERATED} <==")
            sys.stdout.write(text)
    return rc


def _cmd_skeleton(args) -> int:
    try:
        sys.stdout.write(skeleton_ai_node_yaml(args.id, args.type, args.memory_gib, args.admin_cidr or []))
    except AiNodeError as e:
        print(f"ai_nodes: {e.one_line()}", file=sys.stderr)
        return 2
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m app.ai_nodes", description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("render", "check"):
        p = sub.add_parser(name)
        p.add_argument("--site", required=True, help="path to the site repository checkout")
        p.add_argument("--values", default=DEFAULT_VALUES, help=f"values file inside the site (default {DEFAULT_VALUES})")
    sub.choices["render"].add_argument("--ai-node", action="append", metavar="ID", help="render only this node (repeatable)")
    sub.choices["render"].add_argument("--write", action="store_true", help="write ai-nodes/<id>/desired.yaml instead of printing")
    sk = sub.add_parser("skeleton", help="print an ai-node.yaml skeleton")
    sk.add_argument("--id", required=True)
    sk.add_argument("--type", required=True, choices=sorted(TYPE_OS))
    sk.add_argument("--memory-gib", type=float)
    sk.add_argument("--admin-cidr", action="append")
    args = ap.parse_args(argv)
    return {"render": _cmd_render, "check": _cmd_check, "skeleton": _cmd_skeleton}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
