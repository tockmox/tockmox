class _Flow(dict):
    pass


class _FlowList(list):
    pass


class _Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


_Dumper.add_representer(dict, lambda d, v: d.represent_mapping("tag:yaml.org,2002:map", v.items()))
_Dumper.add_representer(_Flow, lambda d, v: d.represent_mapping("tag:yaml.org,2002:map", v.items(), flow_style=True))
_Dumper.add_representer(_FlowList, lambda d, v: d.represent_sequence("tag:yaml.org,2002:seq", v, flow_style=True))
_Dumper.add_representer(list, lambda d, v: d.represent_sequence("tag:yaml.org,2002:seq", v))


def _styled(desired: dict) -> dict:
    """The same data with flow style on the short leaves, so a model line reads on one line. Key order is fixed
    here, not sorted: it is the contract's order, and it is the same on every run."""
    d = copy.deepcopy(desired)
    for inst in d["instances"]:
        inst["auth"] = _Flow(inst["auth"])
        for m in inst["models"]:
            m["artifact"] = _Flow(m["artifact"])
            m["aliases"] = _FlowList(m["aliases"])
    for k in ("enginePorts", "engineAllowFrom", "exporterPorts", "exporterAllowFrom", "adminCidrs", "adminPorts"):
        d["firewall"][k] = _FlowList(d["firewall"][k])
    d["exporters"] = _Flow(d["exporters"])
    d["modelsPresent"] = [_Flow({"model": p["model"], "artifact": _Flow(p["artifact"]), "stage": p["stage"]})
                          for p in d["modelsPresent"]]
    return d


def dump_desired(desired: dict, values_path: str = DEFAULT_VALUES) -> str:
    body = yaml.dump(_styled(desired), Dumper=_Dumper, sort_keys=False, default_flow_style=False, width=4096,
                     allow_unicode=False, indent=2)
    return HEADER.format(values=values_path, id=desired["aiNodeId"]) + "\n" + body


