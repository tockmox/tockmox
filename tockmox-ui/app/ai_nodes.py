# ---------------------------------------------------------------- errors

class AiNodeError(ValueError):
    """A refusal. `problems` is a list of (name, sentence); the name is the invariant that fired, so a test, a CI
    log and a person can all say which rule it was. str() is one problem per line, `name: sentence`."""

    def __init__(self, problems, *, node: str = ""):
        if isinstance(problems, tuple):
            problems = [problems]
        self.problems: list[tuple[str, str]] = list(problems)
        self.node = node
        super().__init__("\n".join(f"{n}: {t}" for n, t in self.problems))

    @property
    def names(self) -> list[str]:
        return [n for n, _ in self.problems]

    def one_line(self) -> str:
        return "; ".join(f"{n}: {t}" for n, t in self.problems)


class SchemaUnavailable(RuntimeError):
    """jsonschema is not importable, or a schema file cannot be found. Not a defect in the site: exit 2."""


# ---------------------------------------------------------------- YAML for authored files
#
# YAML 1.1 (PyYAML, Ansible) reads an unquoted off, on, yes, no, y and n as booleans, so `filevault: off`, which
# reads naturally, arrives as False. The toolkit loads ai-node.yaml with Ansible's loader, the renderer with this
# one; if they disagreed the toolkit would see False where the renderer saw "off". So the authored file is loaded
# strictly: only true and false are booleans, and the ambiguous words are REFUSED with the line number, which
# forces the quoted form that every loader agrees on. Duplicate keys are refused too (a repeated key silently
# keeps the last one).

_AMBIGUOUS = "tag:tockmox.com,2026:ambiguous-bool"


class _StrictLoader(yaml.SafeLoader):
    pass


_StrictLoader.yaml_implicit_resolvers = {
    k: [(t, r) for t, r in v if t not in ("tag:yaml.org,2002:bool", "tag:yaml.org,2002:timestamp")]
    for k, v in yaml.SafeLoader.yaml_implicit_resolvers.items()}
_StrictLoader.add_implicit_resolver("tag:yaml.org,2002:bool", re.compile(r"^(?:true|True|TRUE|false|False|FALSE)$"),
                                    list("tTfF"))
_StrictLoader.add_implicit_resolver(_AMBIGUOUS, re.compile(r"^(?:yes|Yes|YES|no|No|NO|on|On|ON|off|Off|OFF|y|Y|n|N)$"),
                                    list("yYnNoO"))


def _ambiguous(loader, node):
    raise yaml.constructor.ConstructorError(
        None, None,
        f"the bare word {node.value!r} is a boolean to some YAML loaders and a string to others; write "
        f"\"{node.value}\" in quotes (or true / false for a boolean)", node.start_mark)


def _strict_mapping(loader, node, deep=False):
    seen = set()
    for k, _ in node.value:
        key = loader.construct_object(k, deep=True)
        if key in seen:
            raise yaml.constructor.ConstructorError(None, None, f"the key {key!r} appears twice", k.start_mark)
        seen.add(key)
    return yaml.SafeLoader.construct_mapping(loader, node, deep)


_StrictLoader.add_constructor(_AMBIGUOUS, _ambiguous)
_StrictLoader.construct_mapping = _strict_mapping


def load_authored(text: str, where: str) -> dict:
    try:
        doc = yaml.load(text, Loader=_StrictLoader)
    except yaml.YAMLError as e:
        mark = getattr(e, "problem_mark", None)
        line = f" (line {mark.line + 1})" if mark else ""
        why = getattr(e, "problem", None) or str(e)
        raise AiNodeError(("yaml", f"{where}{line}: {why}")) from None
    if not isinstance(doc, dict):
        raise AiNodeError(("yaml", f"{where}: must be a mapping at the top level, got {type(doc).__name__}"))
    return doc


# ---------------------------------------------------------------- schemas

def _schema_dirs() -> list[Path]:
    here = Path(__file__).resolve()
    dirs = []
    if os.environ.get("TOCKMOX_AI_NODE_SCHEMA_DIR"):
        dirs.append(Path(os.environ["TOCKMOX_AI_NODE_SCHEMA_DIR"]))
    # the image: /srv/app/ai_nodes.py with /srv/ai-node/schema; the repository: <root>/ai-node/schema
    dirs += [here.parents[1] / "ai-node" / "schema", here.parents[2] / "ai-node" / "schema"]
    return dirs


_SCHEMA_CACHE: dict[str, dict] = {}


def _schema(name: str) -> dict:
    if name not in _SCHEMA_CACHE:
        for d in _schema_dirs():
            p = d / name
            if p.is_file():
                _SCHEMA_CACHE[name] = json.loads(p.read_text(encoding="utf-8"))
                break
        else:
            raise SchemaUnavailable(f"{name} not found in {', '.join(str(d) for d in _schema_dirs())}; "
                                    "set TOCKMOX_AI_NODE_SCHEMA_DIR to the directory that holds it")
    return _SCHEMA_CACHE[name]


def schema_errors(doc, name: str) -> list[str]:
    """Every violation of the named schema as `path: message`, sorted. Needs jsonschema."""
    try:
        import jsonschema
    except ImportError:
        raise SchemaUnavailable("the python package jsonschema is not installed, so the ai-node files cannot be "
                                "validated: pip install 'jsonschema>=4.18' (it is in tockmox-ui/requirements.txt)") from None
    schema = _schema(name)
    v = jsonschema.Draft202012Validator(schema)
    out = []
    for e in sorted(v.iter_errors(doc), key=lambda e: [str(p) for p in e.absolute_path]):
        path = ".".join(str(p) for p in e.absolute_path) or "(top level)"
        msg = e.message
        if e.validator == "additionalProperties":
            msg += " (unknown keys are refused so a misspelling is not a silent default)"
        elif e.validator == "type" and "string" in str(e.validator_value) and isinstance(e.instance, (int, float)) \
                and not isinstance(e.instance, bool):
            msg += " (quote it: an unquoted number is not a string)"
        out.append(f"{path}: {msg}")
    return out


def _check_schema(doc, name: str, where: str, code: str):
    errs = schema_errors(doc, name)
    if errs:
        raise AiNodeError([(code, f"{where}: {e}") for e in errs[:12]] +
                          ([(code, f"{where}: and {len(errs) - 12} more")] if len(errs) > 12 else []))


# ---------------------------------------------------------------- the site

@dataclass
class Enrollment:
    """One directory under ai-nodes/. `doc` is None when ai-node.yaml is missing (an orphan desired.yaml) or could
    not be parsed (`error` says why)."""
    dir_id: str
    authored_path: Path
    generated_path: Path
    doc: dict | None = None
    error: AiNodeError | None = None
    orphan: bool = False


@dataclass
class Site:
    root: Path
    values_path: str
    inventory: nm.Inventory | None = None
    lifecycle: ml.Lifecycle | None = None
    source_cidrs: tuple = ()
    scrape_cidrs: tuple = ()
    enrollments: dict = field(default_factory=dict)
    values_error: AiNodeError | None = None

    def rel(self, p: Path) -> str:
        return p.relative_to(self.root).as_posix()


def _cidrs(v, what) -> list[str]:
    """Normalised, de-duplicated and sorted; same normalisation as config.py (strict=False). A /0 is refused."""
    if v is None:
        return []
    if not isinstance(v, list):
        raise AiNodeError(("cidr", f"{what} must be a list of CIDRs"))
    nets = set()
    for c in v:
        try:
            n = ipaddress.ip_network(str(c), strict=False)
        except ValueError:
            raise AiNodeError(("cidr", f"{what}: {c!r} is not a CIDR")) from None
        if n.prefixlen == 0:
            raise AiNodeError(("cidr", f"{what}: {c!r} admits every address; name the range the traffic comes from"))
        nets.add(n)
    return [str(n) for n in sorted(nets, key=lambda n: (n.version, int(n.network_address), n.prefixlen))]


def load_site(site_root, values_path: str = DEFAULT_VALUES) -> Site:
    """Read the site repository. Never raises for a bad file: the problem is kept on the Site (`values_error`, or an
    Enrollment's `error`) so `check` can name each node's state; render() raises it."""
    root = Path(site_root).resolve()
    if not root.is_dir():
        raise AiNodeError(("site", f"{site_root}: not a directory"))
    site = Site(root=root, values_path=values_path)
    vp = (root / values_path)
    try:
        doc = yaml.safe_load(vp.read_text(encoding="utf-8")) or {}
        if not isinstance(doc, dict):
            raise ValueError("the top level must be a mapping")
        raw_in = doc.get("inferenceNodes") or {}
        site.inventory = nm.parse_inventory(raw_in)
        site.lifecycle = ml.parse(doc.get("modelLifecycle") or {})
        gw = raw_in.get("gateway") or {}
        site.source_cidrs = tuple(_cidrs(gw.get("sourceCidrs"), "inferenceNodes.gateway.sourceCidrs"))
        site.scrape_cidrs = tuple(_cidrs(gw.get("scrapeCidrs"), "inferenceNodes.gateway.scrapeCidrs"))
    except AiNodeError as e:
        site.values_error = e
    except (OSError, ValueError, TypeError, AttributeError, yaml.YAMLError, nm.NodeError, ml.LifecycleError) as e:
        site.values_error = AiNodeError(("values", f"{values_path}: {e}"))
    base = root / AI_NODES_DIR
    if base.is_dir():
        for d in sorted(p for p in base.iterdir() if p.is_dir() and not p.name.startswith(".")):
            a, g = d / AUTHORED, d / GENERATED
            if not a.is_file() and not g.is_file():
                continue
            en = Enrollment(d.name, a, g)
            if not a.is_file():
                en.orphan = True
            else:
                try:
                    en.doc = load_authored(a.read_text(encoding="utf-8"), f"{AI_NODES_DIR}/{d.name}/{AUTHORED}")
                except AiNodeError as e:
                    en.error = e
                except OSError as e:
                    en.error = AiNodeError(("yaml", f"{AI_NODES_DIR}/{d.name}/{AUTHORED}: {e}"))
            site.enrollments[d.name] = en
    return site


def enrolled_ids(site: Site) -> list[str]:
    return sorted(site.enrollments)


# ---------------------------------------------------------------- derivation

def _canon(obj) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def _sha(obj) -> str:
    try:
        return hashlib.sha256(_canon(obj).encode("ascii")).hexdigest()
    except TypeError as e:
        raise AiNodeError(("yaml", f"an input value cannot be hashed ({e}); quote dates and other special scalars")) from None


def _pos_int(v):
    if isinstance(v, bool) or v is None:
        return None
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    return v if isinstance(v, int) and v > 0 else None


def _context_tokens(route: nm.Route):
    """The route's context ceiling: params.max_input_tokens or params.num_ctx (Ollama), else modelInfo.max_input_tokens,
    which is where LiteLLM's pre-call check reads it and where sites commonly set it."""
    for src, key in ((route.params, "max_input_tokens"), (route.params, "num_ctx"), (route.model_info or {}, "max_input_tokens")):
        if key in src:
            v = _pos_int(src[key])
            if v is not None:
                return v
    return None


def _merge_defaults(doc: dict) -> dict:
    out = copy.deepcopy(DEFAULTS)
    for k, v in doc.items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            for k2, v2 in v.items():
                if isinstance(v2, dict) and isinstance(out[k].get(k2), dict):
                    out[k][k2] = {**out[k][k2], **v2}
                else:
                    out[k][k2] = v2
        else:
            out[k] = v
    return out


def wired_limit_bounds_mib(memory_gib: float) -> tuple[int, int]:
    """The role's assertion: RAM/2 <= v <= RAM - max(10 GiB, 10% of RAM). Returns (low, high) in MiB."""
    ram = memory_gib * 1024
    return int(-(-ram // 2)), int(ram - max(10 * 1024, 0.10 * ram))


def suggest_wired_limit_mib(memory_gib: float) -> int:
    """87.5% of RAM, clamped into the role's bounds, rounded down to a whole GiB (256 GiB -> 229376)."""
    lo, hi = wired_limit_bounds_mib(memory_gib)
    v = min(int(memory_gib * 1024 * 0.875), hi)
    v = (v // 1024) * 1024
    return max(v, lo) if lo <= hi else v


def _revision_problem(kind: str, rev: str) -> str:
    if kind == "huggingface":
        return "" if HF_REV.match(rev or "") else "a 40-hex commit sha"
    if kind in ("ollama", "modelkit"):
        return "" if DIGEST.match(rev or "") else "a manifest digest, sha256:<64 hex>"
    return "a supported source kind"


def derive(site: Site, ai_node_id: str, doc: dict) -> dict:
    """Pure: the desired.yaml dict for one validated ai-node.yaml. Raises AiNodeError listing every invariant that
    fired (not just the first), each by name."""
    inv, lc = site.inventory, site.lifecycle
    cfg = _merge_defaults(doc)
    P: list[tuple[str, str]] = []

    def bad(name, text):
        P.append((name, f"node {ai_node_id}: {text}"))

    node = inv.node(ai_node_id)
    if node is None:
        raise AiNodeError(("unknown-node",
                           f"ai-nodes/{ai_node_id}/ai-node.yaml names aiNodeId {ai_node_id!r}, which is not in "
                           f"inferenceNodes.nodes of {site.values_path}. Add the node there (the UI's Add node page "
                           "does), or delete the ai-nodes directory if the machine is gone."), node=ai_node_id)

    fam = cfg["os"].get("family")
    want = TYPE_OS.get(node.type, "any")
    if want != "any" and fam != want:
        bad("os-type-mismatch", f"ai-node.yaml says os.family {fam!r} but the node's type {node.type!r} runs {want}")
    macos = fam == "macos"

    # firewall inputs
    admin = engine_from = exporter_from = []
    try:
        admin = _cidrs(cfg["access"].get("adminCidrs"), "access.adminCidrs")
        engine_from = list(site.source_cidrs)
        exporter_from = list(site.scrape_cidrs) or engine_from
    except AiNodeError as e:
        P.extend(e.problems)
    if not admin:
        bad("empty-allow-from", "access.adminCidrs is empty: the firewall would admit no administrator and the "
            "toolkit refuses to load it. List the networks you manage this machine from")
    if not engine_from:
        bad("empty-allow-from", f"inferenceNodes.gateway.sourceCidrs is empty in {site.values_path}: the firewall "
            "would admit no gateway. List the networks inference traffic arrives from (on k3s, the cluster nodes' "
            "addresses, because pod traffic leaves through the node)")
    if not exporter_from and engine_from:
        bad("empty-allow-from", "no network may scrape the exporters")

    # ports
    tele = cfg["telemetry"]
    exporters = {"node_exporter": tele["nodeExporterPort"]}
    if macos:
        exporters["macmon"] = tele["macmonPort"]
    for name, port in (("node_exporter", exporters["node_exporter"]), ("macmon", exporters.get("macmon"))):
        declared = node.metrics.get(name)
        if port is not None and declared is not None and declared != port:
            bad("exporter-port-mismatch", f"inferenceNodes says {name} is on port {declared} but ai-node.yaml "
                f"telemetry says {port}; Prometheus would scrape a port nothing listens on. Make them agree")
    admin_ports = [SSH_PORT] + ([SCREEN_PORT] if cfg["access"].get("screenSharing") else [])
    owners: dict[int, list[str]] = {}
    for ep in node.endpoints:
        owners.setdefault(ep.port, []).append(f"endpoint {ep.id}")
    for name, port in exporters.items():
        owners.setdefault(port, []).append(f"exporter {name}")
    for port in admin_ports:
        owners.setdefault(port, []).append("administration" if port == SSH_PORT else "screen sharing")
    for port, who in sorted(owners.items()):
        if len(who) > 1:
            bad("port-collision", f"port {port} is claimed by {' and '.join(who)}; one port can serve one thing")

    # wired limit
    gpu = cfg.get("gpu") or {}
    if macos and gpu.get("wiredLimitMiB") is not None and node.memory_gib() is not None:
        v, mem = gpu["wiredLimitMiB"], node.memory_gib()
        lo, hi = wired_limit_bounds_mib(mem)
        if not lo <= v <= hi:
            bad("wired-limit-out-of-range", f"gpu.wiredLimitMiB {v} is outside {lo}..{hi} MiB for {mem:g} GiB of memory "
                f"(RAM/2 <= value <= RAM - max(10 GiB, 10% of RAM)); {suggest_wired_limit_mib(mem)} is the proposal")

    unknown_engines = sorted(set(cfg["engines"]) - set(nm.ENGINES))
    if unknown_engines:
        bad("unknown-engine", f"ai-node.yaml engines names {unknown_engines}, not engines this version knows "
            f"({', '.join(sorted(nm.ENGINES))})")

    # instances
    routes = sorted(inv.routes_on(ai_node_id), key=lambda r: r.alias)
    by_ep: dict[str, list[nm.Route]] = {}
    for r in routes:
        by_ep.setdefault(r.endpoint, []).append(r)
    entries: dict[str, ml.Entry] = {}
    model_ok: dict[str, bool] = {}
    for r in routes:
        if r.model in model_ok:
            continue
        model_ok[r.model] = False
        e = lc.by_model(r.model)
        if e is None:
            bad("no-catalog-entry", f"route {r.alias} serves model {r.model!r}, which has no entry in "
                f"modelLifecycle.catalog. Admit it first (the Models page proposes the entry); a route to an "
                "uncatalogued model has no revision to pin")
            continue
        entries[r.model] = e
        if e.source.kind == "hosted":
            bad("hosted-model-on-node", f"route {r.alias}: catalog entry {e.id!r} is a hosted model; an AI node "
                "serves open weights it holds")
            continue
        if e.stage == "rejected":
            bad("rejected-model-routed", f"route {r.alias}: catalog entry {e.id!r} was rejected "
                f"({(e.rejection or {}).get('reason', '?')}) and is routed nowhere; remove the route")
            continue
        if e.stage == "retired":
            bad("retired-model-routed", f"route {r.alias}: catalog entry {e.id!r} is retired but still routed here; "
                "re-point or remove the route first (a retired model's files are removed from the node)")
            continue
        miss = _revision_problem(e.source.kind, e.source.revision)
        if miss:
            bad("unpinned-revision", f"route {r.alias}: catalog entry {e.id!r} ({e.source.kind} {e.source.ref}) has "
                + ("no pinned revision" if not e.source.revision else f"revision {e.source.revision!r}, which is not pinned")
                + f". Set source.revision to {miss}. A node installs only a pinned build, so a floating tag could "
                "put different bytes on two nodes")
            continue
        model_ok[r.model] = True

    instances = []
    for ep in sorted(node.endpoints, key=lambda e: e.id):
        rs = by_ep.get(ep.id)
        if not rs:
            continue
        by_model: dict[str, list[nm.Route]] = {}
        for r in rs:
            by_model.setdefault(r.model, []).append(r)
        if ep.engine in SINGLE_MODEL_ENGINES and len(by_model) > 1:
            bad("two-models-one-endpoint", f"endpoint {ep.id} ({ep.engine}) serves one model per process but routes "
                f"{', '.join(sorted(by_model))} reach it. Give each model its own endpoint and port")
        # the -next rule is nodes.gateway_routes': production = every route that does not end in -next
        sub = nm.Inventory(nodes=[node], routes=list(rs))
        prod = nm.gateway_routes(sub, "production")
        if prod and len(prod) != len(rs):
            bad("next-on-production-endpoint", f"endpoint {ep.id} serves production alias "
                f"{sorted(r.alias for r in prod)} and candidate alias "
                f"{sorted(r.alias for r in rs if r.alias.endswith(nm.NEXT))} together. A candidate must not share a "
                "process, or a port, with production: give the -next route its own endpoint")
        gateway = "production" if prod else "eval"
        models = []
        for model in sorted(by_model):
            if not model_ok.get(model):
                continue
            e = entries[model]
            ctx = [c for c in (_context_tokens(r) for r in by_model[model]) if c is not None]
            models.append({
                "model": model,
                "artifact": _artifact(e),
                "aliases": sorted(r.alias for r in by_model[model]),
                "contextTokens": max(ctx) if ctx else None,
            })
        instances.append({"id": ep.id, "engine": ep.engine, "port": ep.port, "models": models,
                          "gateway": gateway, "auth": {"secretRef": ep.auth_secret or None}})

    if P:
        raise AiNodeError(P, node=ai_node_id)

    present = [{"model": m, "artifact": _artifact(entries[m]), "stage": entries[m].stage}
               for m in sorted(entries) if entries[m].stage in ("candidate", "promoted")]
    inputs = {
        "aiNode": doc,
        "gateway": {"sourceCidrs": list(site.source_cidrs), "scrapeCidrs": list(site.scrape_cidrs)},
        "node": {"id": node.id, "type": node.type, "metrics": dict(sorted(node.metrics.items())),
                 "endpoints": [{"id": e.id, "engine": e.engine, "url": e.url, "authSecret": e.auth_secret}
                               for e in sorted(node.endpoints, key=lambda e: e.id)]},
        "routes": [{"alias": r.alias, "endpoint": r.endpoint, "model": r.model, "contextTokens": _context_tokens(r)}
                   for r in routes],
        "catalog": [{"id": e.id, "model": e.model, "stage": e.stage, "source": e.source.as_dict()}
                    for e in sorted(entries.values(), key=lambda e: e.model)],
    }
    return {
        "schema": DESIRED_SCHEMA_ID,
        "aiNodeId": ai_node_id,
        "inputsSha256": _sha(inputs),
        "instances": instances,
        "firewall": {
            "enginePorts": sorted({i["port"] for i in instances}),
            "engineAllowFrom": engine_from,
            "exporterPorts": sorted(set(exporters.values())),
            "exporterAllowFrom": exporter_from,
            "adminCidrs": admin,
            "adminPorts": admin_ports,
        },
        "exporters": exporters,
        "modelsPresent": present,
    }


def _artifact(e: ml.Entry) -> dict:
    return {"kind": e.source.kind, "ref": e.source.ref, "revision": e.source.revision}


