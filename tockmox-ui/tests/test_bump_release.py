APPS = "bootstrap/applications"


def app_file(layer, rev="v0.7.2", quoted=False, comment=""):
    r = f'"{rev}"' if quoted else rev
    return (f"# Generated by tockmox-install.sh v0.7.2.\napiVersion: argoproj.io/v1alpha1\nkind: Application\n"
            f"metadata:\n  name: tockmox-{layer}\nspec:\n  sources:\n    - repoURL: https://github.com/tockmox/tockmox\n"
            f"      targetRevision: {r}{comment}\n      path: charts/tockmox-{layer}\n"
            f"    - repoURL: https://forge.example/site.git\n      targetRevision: main\n      ref: site\n")


def forge(**over):
    fg = tc.Forge()
    files = {f"{APPS}/tockmox-platform.yaml": app_file("platform"),
             f"{APPS}/tockmox-observability.yaml": app_file("observability", quoted=True, comment="   # pinned"),
             f"{APPS}/tockmox-ai.yaml": app_file("ai"), "bootstrap/root.yaml": "kind: Application\n"}
    files.update(over)
    fg.files["main"].update(files)
    return fg


PF = [{"label": "Every layer is Synced", "state": "ok", "manual": False},
      {"label": "No critical alerts are firing", "state": "ok", "manual": False},
      {"label": "The built-in forge is upgraded first", "state": "unknown", "manual": True}]


def bump(frm="v0.7.2", to="v0.7.3", kind="patch", pf=None):
    return {"from": frm, "to": to, "kind": kind, "preflight": pf or PF}


def open_bump(s, t, **tok):
    return oc.confirm_and_open(s, "bump-release", t, preferred_username="jeff", **tok)


