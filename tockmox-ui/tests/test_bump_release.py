"""Platform > Updates: open the version bump as a change you approve.

  plan     every layer's Application under bootstrap/applications has its targetRevision moved from the running
           release to the target (indent, quotes and comment kept); a line naming the site's own branch is left
           alone; one commit, one change, which waits for an approval; who asked is recorded
  refuse   a layer on a third release (the guide moves one release to another); no Application on the running
           release; a preflight that is not green; anything but two release tags and a kind
  page     offered only with a verified feed, a green preflight and no breaking change on the way (those edits go
           in the same commit, by hand); the change's description carries the preflight, and what only a person can
           check (the built-in forge upgraded first; for a minor, the guide's steps 2 to 4) is listed as such

Run from tockmox-ui/: python -m pytest tests/test_bump_release.py
"""
