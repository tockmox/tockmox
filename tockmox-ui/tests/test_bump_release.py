class Checker:
    releases = []

    def __init__(self, *a, **k):
        self.state = feedmod.FeedState(enabled=True, verified=True, releases=list(Checker.releases))

    def check(self, force=False, now=None):
        return self.state


def page(tmp_path, monkeypatch, releases, on=True, apps=None):
    Checker.releases = releases
    monkeypatch.setattr(feedmod, "UpdateChecker", Checker)
    fg = forge()
    c, csrf, idp, am, kube, sent = base.console(tmp_path, actions=tc.actions_on(tmp_path) if on else None,
                                                forge=fg.handler, apps=apps)
    return c, fg


PATCH = [{"version": "0.7.3", "breaking": [], "security": False}]


def test_the_page_offers_it_and_the_confirm_panel_shows_every_file(tmp_path, monkeypatch):
    c, fg = page(tmp_path, monkeypatch, PATCH)
    t = c.get("/upgrade").text
    assert "/actions/confirm?kind=bump-release&amp;to=0.7.3" in t, t[:3000]
    r = c.get("/actions/confirm?kind=bump-release&to=0.7.3")
    assert r.status_code == 200, r.text[:800]
    assert "Upgrade Tockmox from v0.7.2 to v0.7.3?" in r.text
    assert r.text.count("+      targetRevision: v0.7.3") == 2 and "tockmox-observability.yaml" in r.text
    assert "upgrade-forge" in r.text and "step 1)" in r.text, "the forge-first step and the notes are hand checks"
    assert "migrates its own database (the guide&#39;s step 2)" in r.text, "a patch backs up only for a migrating app"
    assert "steps 2 and 3" not in r.text and "steps 2 to 4" not in r.text
    assert fg.opened == []


@pytest.mark.parametrize("to,steps", [("0.8.0", "steps 2 and 3"), ("1.0.0", "steps 2 to 4")])
def test_a_minor_or_major_carries_the_guides_steps(tmp_path, monkeypatch, to, steps):
    c, _ = page(tmp_path, monkeypatch, [{"version": to, "breaking": [], "security": False}])
    r = c.get(f"/actions/confirm?kind=bump-release&to={to}")
    assert r.status_code == 200 and steps in r.text, r.text[:800]
    assert "migrates its own database" not in r.text


def test_a_breaking_change_on_the_way_means_no_button_and_a_refusal(tmp_path, monkeypatch):
    c, _ = page(tmp_path, monkeypatch, [{"version": "0.7.3", "breaking": ["rename x to y"], "security": False}])
    t = c.get("/upgrade").text
