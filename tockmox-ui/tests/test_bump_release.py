def test_every_layer_moves_and_nothing_else_in_one_change(tmp_path):
    s, fg, _ = tc.service(tmp_path, forge())
    code, out = open_bump(s, bump())
    assert code == 200 and out["result"] == "done", out
    who, b = fg.contents_posts[-1]
    assert who == "tockmox-change-bot" and b["new_branch"].startswith("tockmox/console-upgrade-v0.7.3-")
    got = {f["path"]: base64.b64decode(f["content"]).decode() for f in b["files"]}
    assert sorted(got) == [f"{APPS}/tockmox-ai.yaml", f"{APPS}/tockmox-observability.yaml", f"{APPS}/tockmox-platform.yaml"]
    assert got[f"{APPS}/tockmox-platform.yaml"] == app_file("platform").replace("targetRevision: v0.7.2", "targetRevision: v0.7.3")
    assert got[f"{APPS}/tockmox-observability.yaml"] == app_file("observability", rev="v0.7.3", quoted=True, comment="   # pinned")
    assert all(t.count("targetRevision: main") == 1 for t in got.values()), "the site's own branch is left alone"
    assert all(f["operation"] == "update" and f["sha"] == tc.sha_of(fg.files["main"][f["path"]]) for f in b["files"])
    _, pr = fg.opened[-1]
    assert pr["title"] == "Upgrade Tockmox from v0.7.2 to v0.7.3"
    assert "- ok: Every layer is Synced" in pr["body"] and "check by hand" in pr["body"]
    assert "- The built-in forge is upgraded first" in pr["body"] and "Tockmox-Requested-By: jeff" in pr["body"]
    assert fg.reviews == [] and fg.merges == []


def test_asking_twice_opens_one_change(tmp_path):
    s, fg, _ = tc.service(tmp_path, forge())
    open_bump(s, bump())
    fg.pulls[8]["head"]["ref"] = fg.contents_posts[-1][1]["new_branch"]
    code, out = open_bump(s, bump())
    assert code == 200 and "already open as #8" in out["detail"], out
    assert len(fg.opened) == 1


def test_a_layer_on_a_third_release_is_refused_and_named(tmp_path):
    s, fg, _ = tc.service(tmp_path, forge(**{f"{APPS}/tockmox-ai.yaml": app_file("ai", rev="v0.7.1")}))
    code, out = open_bump(s, bump())
    assert code == 403 and "tockmox-ai.yaml (v0.7.1)" in out["reason"], out
    assert fg.opened == []


def test_no_application_on_the_running_release_opens_nothing(tmp_path):
    s, fg, _ = tc.service(tmp_path, forge())
    code, out = open_bump(s, bump(frm="v0.6.9", to="v0.7.3"))
    assert code == 403, out
    assert fg.opened == []


def test_it_needs_a_fresh_sign_in(tmp_path):
    assert act.step_up("bump-release")
    s, fg, _ = tc.service(tmp_path, forge())
    import time
    code, out = open_bump(s, bump(), auth_time=time.time() - 3600)
    assert code == 403 and fg.opened == [], out


