"""The ai-node renderer (app/ai_nodes.py): site values + ai-node.yaml -> desired.yaml.

What these prove: the render of a generic fixture site is the committed golden, byte for byte and in any input
order; every invariant the contract names refuses with its own name; `check` sees a hand-edited, stale, missing
and orphaned desired.yaml; the skeleton the UI offers validates against the schema and renders; a node with no
ai-node.yaml is left alone. What they do not prove: that a converger applies the file (the toolkit's tests).
Run from tockmox-ui/: python -m pytest tests
"""
