# ---------------------------------------------------------------- helpers

def make_site(tmp_path, values=None, ai=None, node="example-mac"):
    """A copy of the fixture site; `values(doc)` and `ai(doc)` mutate the parsed files in place."""
    root = tmp_path / "site"
    shutil.copytree(FIX, root)
    if values:
        p = root / "site/values/models.yaml"
        d = yaml.safe_load(p.read_text())
        values(d)
        p.write_text(yaml.safe_dump(d, sort_keys=False))
    if ai:
        p = root / f"ai-nodes/{node}/ai-node.yaml"
        d = yaml.safe_load(p.read_text())
        ai(d)
        p.write_text(yaml.safe_dump(d, sort_keys=False))
    return root


def render_text(root, nid="example-mac"):
    return an.render(an.load_site(root), nid)


def refusal(root, nid="example-mac"):
    with pytest.raises(an.AiNodeError) as e:
        render_text(root, nid)
    return e.value


def node_of(d, nid="example-mac"):
    return next(n for n in d["inferenceNodes"]["nodes"] if n["id"] == nid)


def route_of(d, alias):
    return next(r for r in d["inferenceNodes"]["routes"] if r["alias"] == alias)


def entry_of(d, model):
    return next(e for e in d["modelLifecycle"]["catalog"] if e["model"] == model)


