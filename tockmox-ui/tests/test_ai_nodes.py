def _reversed(o):
    if isinstance(o, dict):
        return {k: _reversed(v) for k, v in reversed(list(o.items()))}
    if isinstance(o, list):
        return [_reversed(v) for v in reversed(o)]
    return o


def test_byte_stable_when_input_order_is_shuffled(tmp_path):
    root = make_site(tmp_path)
    for rel in ("site/values/models.yaml", "ai-nodes/example-mac/ai-node.yaml"):
        p = root / rel
        d = yaml.safe_load(p.read_text())
        # lists in ai-node.yaml are values the author ordered (sshAllowUsers, extraArgs); reverse keys only there
        p.write_text(yaml.safe_dump(_reversed(d) if rel.startswith("site") else
                                    dict(reversed(list(d.items()))), sort_keys=False))
    assert render_text(root)[0] == render_text(FIX)[0]


