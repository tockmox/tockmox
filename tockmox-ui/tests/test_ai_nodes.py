def test_render_content():
    _, d = render_text(FIX)
    assert d["schema"] == "tockmox.ai-node.desired/v1" and d["aiNodeId"] == "example-mac"
    assert [i["id"] for i in d["instances"]] == ["mlx-lm-8080", "mlx-lm-8082", "ollama-11434"]
    prod, nxt, oll = d["instances"]
    assert (prod["engine"], prod["port"], prod["gateway"]) == ("mlx-lm", 8080, "production")
    assert (nxt["engine"], nxt["port"], nxt["gateway"]) == ("mlx-lm", 8082, "eval")
    assert nxt["models"][0]["aliases"] == ["local-medium-next"] and nxt["models"][0]["contextTokens"] == 65536
    assert prod["models"][0]["artifact"] == {"kind": "huggingface", "ref": "mlx-community/Example-27B-8bit", "revision": HF}
    assert prod["auth"] == {"secretRef": None} and oll["auth"] == {"secretRef": "example-ollama-key"}
    # ollama: two models on one endpoint; num_ctx is the context, an embedding route with none is null
    assert [(m["model"], m["contextTokens"]) for m in oll["models"]] == [("example-coder:30b", 16384), ("example-embed", None)]
    assert d["firewall"] == {
        "enginePorts": [8080, 8082, 11434], "engineAllowFrom": ["198.51.100.0/24"],
        "exporterPorts": [9100, 9101], "exporterAllowFrom": ["198.51.100.0/24"],
        "adminCidrs": ["203.0.113.0/24"], "adminPorts": [22]}
    assert d["exporters"] == {"node_exporter": 9100, "macmon": 9101}
    # candidate and promoted entries routed here; the retired entry and the other node's model are absent
    assert [(p["model"], p["stage"]) for p in d["modelsPresent"]] == [
        ("example-coder:30b", "promoted"), ("example-embed", "promoted"),
        ("mlx-community/Example-2-27B-8bit", "candidate"), ("mlx-community/Example-27B-8bit", "promoted")]


